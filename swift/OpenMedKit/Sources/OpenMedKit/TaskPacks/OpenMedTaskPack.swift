import Foundation

/// Value-free task pack failures.
///
/// The raw value is the stable reason code. No case carries a repository id,
/// path, URL, manifest string or input text, so errors are safe to log.
public enum OpenMedTaskPackError: String, Error, Equatable, Sendable, CaseIterable, LocalizedError {
    /// The bundled `task_packs.json` resource is missing or unreadable.
    case manifestUnavailable = "manifest_unavailable"
    /// The manifest is malformed, declares an unknown field or breaks a
    /// cross-field rule (ranks, licenses, notices, formats).
    case manifestInvalid = "manifest_invalid"
    /// The manifest schema name or major version is not supported.
    case schemaUnsupported = "schema_unsupported"
    /// The manifest does not declare the requested pack.
    case unknownPack = "unknown_pack"
    /// The manifest records no Apple candidate for the pack.
    case noCandidate = "no_candidate"
    /// Every candidate needs MLX, which cannot run on the iOS Simulator.
    case unsupportedOnSimulator = "unsupported_on_simulator"
    /// Every candidate needs MLX, which needs Apple silicon.
    case unsupportedPlatform = "unsupported_platform"
    /// No candidate is cached and downloading was not allowed.
    case notCached = "not_cached"
    /// Downloading was allowed but no candidate could be downloaded.
    case downloadFailed = "download_failed"
    /// A candidate was available locally but no candidate could be loaded.
    case loadFailed = "load_failed"
    /// The pack was used before `prepare(store:allowDownload:)` succeeded.
    case notPrepared = "not_prepared"

    /// Stable reason code for logs and metrics.
    public var reason: String { rawValue }

    public var errorDescription: String? {
        switch self {
        case .manifestUnavailable:
            return "The bundled task pack manifest is unavailable."
        case .manifestInvalid:
            return "The task pack manifest is invalid."
        case .schemaUnsupported:
            return "The task pack manifest schema is not supported."
        case .unknownPack:
            return "The task pack is not declared in the manifest."
        case .noCandidate:
            return "The task pack has no model candidate for Apple platforms."
        case .unsupportedOnSimulator:
            return "The task pack's MLX candidates cannot run on the iOS Simulator."
        case .unsupportedPlatform:
            return "The task pack's MLX candidates need Apple silicon."
        case .notCached:
            return "No task pack candidate is cached and downloading was not allowed."
        case .downloadFailed:
            return "No task pack candidate could be downloaded."
        case .loadFailed:
            return "No task pack candidate could be loaded."
        case .notPrepared:
            return "The task pack has not been prepared."
        }
    }
}

/// The notice a kit must show with a pack's output.
///
/// The text comes from the bundled manifest; apps can localize by `key`.
public struct OpenMedTaskPackNotice: Equatable, Hashable, Sendable {
    /// Stable notice key, for example `openmed.notice.pii.review_required`.
    public let key: String
    /// Default English notice text.
    public let text: String
}

/// One ordered model candidate of a pack for Apple platforms.
public struct OpenMedTaskPackCandidate: Equatable, Hashable, Sendable {
    /// Position in the manifest's candidate order, starting at 1.
    public let rank: Int
    /// Hugging Face repository id of the model snapshot.
    public let repoID: String
    /// Parameter count recorded in the manifest.
    public let paramCount: Int
    /// Permissive license recorded in the manifest.
    public let license: String
    /// Model format the Apple runtime loads (`mlx-fp`).
    public let format: String
}

/// A task pack as declared for the Apple runtime in `task_packs.json`.
public struct OpenMedTaskPackDefinition: Equatable, Sendable {
    /// Pack identifier, for example `pii`.
    public let packID: String
    /// Semantic version of the pack declaration.
    public let version: String
    /// Job the pack performs, for example `pii_detection`.
    public let task: String
    /// Labels every candidate is guaranteed to emit, sorted.
    public let canonicalLabels: [String]
    /// Notice the app must show with the pack's output.
    public let notice: OpenMedTaskPackNotice
    /// Model format of the Apple runtime entry.
    public let format: String
    /// Apple candidates in rank order. Empty when the manifest records
    /// `no_candidate`.
    public let candidates: [OpenMedTaskPackCandidate]
}

/// The portable task pack manifest, read from the bundled `task_packs.json`.
///
/// The resource is a byte-identical copy of `openmed/core/data/task_packs.json`
/// generated by `scripts/manifest/build_task_packs.py`. OpenMedKit reads the
/// Apple runtime entry and does not re-run the selection. Decoding fails closed
/// on another schema, another major version, an undeclared field or a broken
/// cross-field rule.
public struct OpenMedTaskPackManifest: Equatable, Sendable {
    /// Manifest schema name.
    public static let schema = "openmed.task_packs"
    /// Supported manifest major version.
    public static let supportedMajorVersion = 1
    /// Runtime key OpenMedKit reads.
    public static let runtime = "apple"
    /// Model format the Apple runtime loads.
    public static let appleFormat = "mlx-fp"
    /// Bundled resource file name.
    public static let resourceFile = "task_packs.json"

    /// Semantic version of the manifest document.
    public let schemaVersion: String
    /// Declared packs by identifier.
    public let packs: [String: OpenMedTaskPackDefinition]

    /// Load the manifest bundled with OpenMedKit.
    ///
    /// - Throws: ``OpenMedTaskPackError/manifestUnavailable`` when the resource
    ///   is missing, or a decoding error from ``decode(_:)``.
    public static func bundled() throws -> OpenMedTaskPackManifest {
        guard let data = bundledResourceData() else {
            throw OpenMedTaskPackError.manifestUnavailable
        }
        return try decode(data)
    }

    /// Bytes of the bundled `task_packs.json`, or `nil` when it is missing.
    public static func bundledResourceData() -> Data? {
        let url =
            Bundle.module.url(forResource: "task_packs", withExtension: "json", subdirectory: "task_packs")
            ?? Bundle.module.url(
                forResource: "task_packs",
                withExtension: "json",
                subdirectory: "Resources/task_packs"
            )
            ?? Bundle.module.url(forResource: "task_packs", withExtension: "json")
        return url.flatMap { try? Data(contentsOf: $0) }
    }

    /// Return the pack with the given identifier.
    ///
    /// - Throws: ``OpenMedTaskPackError/unknownPack``.
    public func pack(_ packID: String) throws -> OpenMedTaskPackDefinition {
        guard let pack = packs[packID] else {
            throw OpenMedTaskPackError.unknownPack
        }
        return pack
    }

    /// Decode and validate manifest bytes.
    ///
    /// - Throws: ``OpenMedTaskPackError/schemaUnsupported`` for another schema
    ///   or major version, ``OpenMedTaskPackError/manifestInvalid`` otherwise.
    public static func decode(_ data: Data) throws -> OpenMedTaskPackManifest {
        guard let root = (try? JSONSerialization.jsonObject(with: data)) as? [String: Any] else {
            throw OpenMedTaskPackError.manifestInvalid
        }
        guard root["schema"] as? String == schema else {
            throw OpenMedTaskPackError.schemaUnsupported
        }
        guard let schemaVersion = root["schema_version"] as? String,
            let major = semanticVersion(schemaVersion)?.major
        else {
            throw OpenMedTaskPackError.manifestInvalid
        }
        guard major == supportedMajorVersion else {
            throw OpenMedTaskPackError.schemaUnsupported
        }
        try requireKeys(root, ["notices", "packs", "schema", "schema_version", "source"])
        guard root["source"] as? String == "models.jsonl",
            let notices = root["notices"] as? [String: Any], !notices.isEmpty,
            let packDocuments = root["packs"] as? [Any], !packDocuments.isEmpty
        else {
            throw OpenMedTaskPackError.manifestInvalid
        }
        var noticeTexts: [String: String] = [:]
        for (key, value) in notices {
            guard isNoticeKey(key), let text = value as? String, !text.isEmpty else {
                throw OpenMedTaskPackError.manifestInvalid
            }
            noticeTexts[key] = text
        }
        var packs: [String: OpenMedTaskPackDefinition] = [:]
        for document in packDocuments {
            let pack = try decodePack(document, notices: noticeTexts)
            guard packs[pack.packID] == nil else {
                throw OpenMedTaskPackError.manifestInvalid
            }
            packs[pack.packID] = pack
        }
        return OpenMedTaskPackManifest(schemaVersion: schemaVersion, packs: packs)
    }

    // MARK: - Decoding

    private static let permissiveLicenses: Set<String> = [
        "apache-2.0", "bsd-2-clause", "bsd-3-clause", "cc-by-4.0", "cc0-1.0", "isc", "mit", "unlicense",
    ]

    private static func decodePack(
        _ value: Any,
        notices: [String: String]
    ) throws -> OpenMedTaskPackDefinition {
        guard let pack = value as? [String: Any] else {
            throw OpenMedTaskPackError.manifestInvalid
        }
        try requireKeys(
            pack,
            ["canonical_labels", "notice_key", "pack_id", "runtimes", "selection", "task", "version"]
        )
        guard let packID = pack["pack_id"] as? String, isIdentifier(packID),
            let version = pack["version"] as? String, semanticVersion(version) != nil,
            let task = pack["task"] as? String, isIdentifier(task),
            let labels = pack["canonical_labels"] as? [String], !labels.isEmpty,
            Set(labels).count == labels.count, labels.allSatisfy(isCanonicalLabel),
            let noticeKey = pack["notice_key"] as? String, let noticeText = notices[noticeKey],
            let selection = pack["selection"] as? [String: Any],
            let licenses = selection["licenses"] as? [String], !licenses.isEmpty,
            Set(licenses).isSubset(of: permissiveLicenses),
            let maxCandidates = integer(selection["max_candidates"]),
            let maxParamCount = integer(selection["max_param_count"]),
            let runtimes = pack["runtimes"] as? [String: Any]
        else {
            throw OpenMedTaskPackError.manifestInvalid
        }
        try requireKeys(runtimes, ["android", "apple", "web"])
        guard let apple = runtimes[runtime] as? [String: Any] else {
            throw OpenMedTaskPackError.manifestInvalid
        }
        try requireKeys(apple, ["candidates", "format", "status"])
        guard apple["format"] as? String == appleFormat,
            let status = apple["status"] as? String,
            let candidateDocuments = apple["candidates"] as? [Any],
            candidateDocuments.count <= maxCandidates
        else {
            throw OpenMedTaskPackError.manifestInvalid
        }
        let candidates = try candidateDocuments.map { document in
            try decodeCandidate(document, licenses: Set(licenses), maxParamCount: maxParamCount)
        }
        guard status == (candidates.isEmpty ? "no_candidate" : "resolved"),
            candidates.map(\.rank) == Array(stride(from: 1, through: candidates.count, by: 1)),
            zip(candidates, candidates.dropFirst()).allSatisfy({ isOrdered($0, $1) })
        else {
            throw OpenMedTaskPackError.manifestInvalid
        }
        return OpenMedTaskPackDefinition(
            packID: packID,
            version: version,
            task: task,
            canonicalLabels: labels.sorted(),
            notice: OpenMedTaskPackNotice(key: noticeKey, text: noticeText),
            format: appleFormat,
            candidates: candidates
        )
    }

    private static func decodeCandidate(
        _ value: Any,
        licenses: Set<String>,
        maxParamCount: Int
    ) throws -> OpenMedTaskPackCandidate {
        guard let candidate = value as? [String: Any] else {
            throw OpenMedTaskPackError.manifestInvalid
        }
        try requireKeys(candidate, ["license", "param_count", "rank", "repo_id"])
        guard let license = candidate["license"] as? String, licenses.contains(license),
            let paramCount = integer(candidate["param_count"]), paramCount >= 1, paramCount <= maxParamCount,
            let rank = integer(candidate["rank"]), rank >= 1,
            let repoID = candidate["repo_id"] as? String, isRepositoryID(repoID)
        else {
            throw OpenMedTaskPackError.manifestInvalid
        }
        return OpenMedTaskPackCandidate(
            rank: rank,
            repoID: repoID,
            paramCount: paramCount,
            license: license,
            format: appleFormat
        )
    }

    private static func isOrdered(_ lhs: OpenMedTaskPackCandidate, _ rhs: OpenMedTaskPackCandidate) -> Bool {
        lhs.paramCount < rhs.paramCount || (lhs.paramCount == rhs.paramCount && lhs.repoID < rhs.repoID)
    }

    /// Fail closed unless the object has exactly the declared keys.
    private static func requireKeys(_ object: [String: Any], _ keys: Set<String>) throws {
        guard Set(object.keys) == keys else {
            throw OpenMedTaskPackError.manifestInvalid
        }
    }

    /// A JSON integer; booleans and fractional numbers are rejected.
    private static func integer(_ value: Any?) -> Int? {
        guard let number = value as? NSNumber, CFGetTypeID(number) != CFBooleanGetTypeID() else {
            return nil
        }
        let integer = number.intValue
        return NSNumber(value: integer) == number ? integer : nil
    }

    private static func semanticVersion(_ value: String) -> (major: Int, minor: Int, patch: Int)? {
        let parts = value.split(separator: ".", omittingEmptySubsequences: false)
        guard parts.count == 3 else { return nil }
        var numbers: [Int] = []
        for part in parts {
            guard !part.isEmpty, part.unicodeScalars.allSatisfy({ ("0"..."9").contains($0) }),
                part == "0" || !part.hasPrefix("0"),
                let number = Int(part)
            else { return nil }
            numbers.append(number)
        }
        return (numbers[0], numbers[1], numbers[2])
    }

    private static func isIdentifier(_ value: String) -> Bool {
        guard let first = value.unicodeScalars.first, ("a"..."z").contains(first), value.unicodeScalars.count <= 64
        else { return false }
        return value.unicodeScalars.allSatisfy { ("a"..."z").contains($0) || ("0"..."9").contains($0) || $0 == "_" }
    }

    private static func isCanonicalLabel(_ value: String) -> Bool {
        guard let first = value.unicodeScalars.first, ("A"..."Z").contains(first), value.unicodeScalars.count <= 64
        else { return false }
        return value.unicodeScalars.allSatisfy { ("A"..."Z").contains($0) || ("0"..."9").contains($0) || $0 == "_" }
    }

    private static func isNoticeKey(_ value: String) -> Bool {
        let parts = value.split(separator: ".", omittingEmptySubsequences: false)
        return parts.count == 4 && parts[0] == "openmed" && parts[1] == "notice"
            && isIdentifier(String(parts[2])) && isIdentifier(String(parts[3]))
    }

    private static func isRepositoryID(_ value: String) -> Bool {
        let parts = value.split(separator: "/", omittingEmptySubsequences: false)
        guard parts.count == 2 else { return false }
        return parts.allSatisfy { part in
            guard let first = part.unicodeScalars.first, part.unicodeScalars.count <= 96,
                ("A"..."Z").contains(first) || ("a"..."z").contains(first) || ("0"..."9").contains(first)
            else { return false }
            return part.unicodeScalars.allSatisfy {
                ("A"..."Z").contains($0) || ("a"..."z").contains($0) || ("0"..."9").contains($0)
                    || $0 == "." || $0 == "_" || $0 == "-"
            }
        }
    }
}

/// Why a candidate cannot run on this device.
public enum OpenMedTaskPackSkipReason: String, Equatable, Sendable {
    /// MLX cannot run on the iOS Simulator.
    case unsupportedOnSimulator = "unsupported_on_simulator"
    /// MLX needs Apple silicon.
    case unsupportedPlatform = "unsupported_platform"
}

/// A manifest candidate this device cannot run, with the reason.
public struct OpenMedTaskPackSkippedCandidate: Equatable, Sendable {
    public let candidate: OpenMedTaskPackCandidate
    public let reason: OpenMedTaskPackSkipReason
}

/// The candidates of a pack this device can use, best first.
///
/// Resolution reads the bundled manifest only. It never downloads, verifies
/// or loads a model and makes no network request.
public struct OpenMedTaskPackResolution: Equatable, Sendable {
    /// Outcome of resolving a pack on this device.
    public enum Status: String, Equatable, Sendable {
        /// At least one candidate can run here.
        case resolved
        /// The manifest records no Apple candidate.
        case noCandidate = "no_candidate"
        /// Every candidate needs MLX and this is the iOS Simulator.
        case unsupportedOnSimulator = "unsupported_on_simulator"
        /// Every candidate needs MLX and this host is not Apple silicon.
        case unsupportedPlatform = "unsupported_platform"
    }

    /// The pack as declared in the manifest.
    public let pack: OpenMedTaskPackDefinition
    /// Outcome on this device.
    public let status: Status
    /// Candidates that can run on this device, in rank order.
    public let candidates: [OpenMedTaskPackCandidate]
    /// Candidates skipped on this device, in rank order, with the reason.
    public let skipped: [OpenMedTaskPackSkippedCandidate]

    /// Repository ids of the usable candidates, best first.
    public var repoIDs: [String] { candidates.map(\.repoID) }

    /// The value-free error `prepare` raises for an unusable resolution.
    var refusal: OpenMedTaskPackError? {
        switch status {
        case .resolved: return nil
        case .noCandidate: return .noCandidate
        case .unsupportedOnSimulator: return .unsupportedOnSimulator
        case .unsupportedPlatform: return .unsupportedPlatform
        }
    }

    /// Resolve a pack for a device with the given MLX support.
    ///
    /// - Parameters:
    ///   - pack: Pack definition from the manifest.
    ///   - mlxSupported: Whether MLX can run in this process.
    ///   - isSimulator: Whether this process is (or simulates) the iOS Simulator.
    static func resolve(
        _ pack: OpenMedTaskPackDefinition,
        mlxSupported: Bool,
        isSimulator: Bool
    ) -> OpenMedTaskPackResolution {
        guard !pack.candidates.isEmpty else {
            return OpenMedTaskPackResolution(pack: pack, status: .noCandidate, candidates: [], skipped: [])
        }
        var usable: [OpenMedTaskPackCandidate] = []
        var skipped: [OpenMedTaskPackSkippedCandidate] = []
        for candidate in pack.candidates {
            if candidate.format == OpenMedTaskPackManifest.appleFormat && !mlxSupported {
                skipped.append(
                    OpenMedTaskPackSkippedCandidate(
                        candidate: candidate,
                        reason: isSimulator ? .unsupportedOnSimulator : .unsupportedPlatform
                    )
                )
            } else {
                usable.append(candidate)
            }
        }
        let status: Status
        if !usable.isEmpty {
            status = .resolved
        } else {
            status = isSimulator ? .unsupportedOnSimulator : .unsupportedPlatform
        }
        return OpenMedTaskPackResolution(pack: pack, status: status, candidates: usable, skipped: skipped)
    }
}

/// Where task packs look for cached model snapshots and, with consent, store
/// downloaded ones. Backed by ``OpenMedModelStore``.
public struct OpenMedTaskPackStore: Sendable {
    /// The default OpenMed MLX cache (`Caches/OpenMed/MLXModels`).
    public static let standard = OpenMedTaskPackStore()

    /// Cache root, or `nil` for the default OpenMed MLX cache.
    public let cacheDirectory: URL?
    /// Repository revision to cache and download.
    public let revision: String
    let session: URLSession

    /// Create a store over an OpenMed MLX cache root.
    ///
    /// - Parameters:
    ///   - cacheDirectory: Cache root, or `nil` for the default cache.
    ///   - revision: Repository revision (default `main`).
    public init(cacheDirectory: URL? = nil, revision: String = "main") {
        self.init(cacheDirectory: cacheDirectory, revision: revision, session: .shared)
    }

    /// Internal transport injection keeps download tests offline.
    init(cacheDirectory: URL?, revision: String, session: URLSession) {
        self.cacheDirectory = cacheDirectory
        self.revision = revision
        self.session = session
    }

    /// The snapshot directory of a candidate when it is completely cached.
    /// Reads the local cache only.
    func readyDirectory(for candidate: OpenMedTaskPackCandidate) throws -> URL? {
        guard
            try OpenMedModelStore.mlxModelCacheState(
                repoID: candidate.repoID,
                revision: revision,
                cacheDirectory: cacheDirectory
            ) == .ready
        else { return nil }
        return try OpenMedModelStore.cachedMLXModelDirectory(
            repoID: candidate.repoID,
            revision: revision,
            cacheDirectory: cacheDirectory
        )
    }

    /// Download a candidate's snapshot. Only called with download consent.
    func download(_ candidate: OpenMedTaskPackCandidate) async throws -> URL {
        try await OpenMedModelStore.downloadMLXModel(
            repoID: candidate.repoID,
            revision: revision,
            cacheDirectory: cacheDirectory,
            session: session
        )
    }
}
