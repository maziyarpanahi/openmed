"""Tests for the declarative generalization function family.

All fixtures are synthetic and generated algorithmically; no real values are
used. Boundary values called out by the task (age 0/89/90/120, 5-digit and
7-character postcodes, leap-day dates) are covered explicitly alongside a wider
formula-generated grid.
"""

from __future__ import annotations

import re
from datetime import date, datetime, timedelta

import pytest

from openmed.core.date_shift import stable_offset_for
from openmed.risk import enforce_kanon
from openmed.structured import (
    COLUMN_TYPE_AGE,
    COLUMN_TYPE_DATE,
    COLUMN_TYPE_ZIP,
    GeneralizationLevel,
    Hierarchy,
    HierarchyError,
    build_enforcement_hierarchies,
    describe_level,
    generalize_value,
    get_hierarchy,
    max_level,
    to_enforce_kanon_hierarchy,
)
from openmed.structured.hierarchies import (
    AGE_MAX,
    AGE_MIN_BAND_WIDTH,
    AGE_TOP_BAND,
    AGE_TOP_THRESHOLD,
    HIERARCHY_SCHEMA_VERSION,
    SUPPORTED_COLUMN_TYPES,
    SUPPRESSED,
)

SECRET = "unit-test-secret-value"

# --------------------------------------------------------------------------- #
# Synthetic, algorithmically generated fixtures                               #
# --------------------------------------------------------------------------- #
AGE_BOUNDARIES = (0, 89, 90, 120)
AGE_GRID = sorted({*AGE_BOUNDARIES, *range(0, AGE_MAX + 1, 7)})

# Five-digit ZIPs and seven-character alphanumeric postcodes, both by formula.
_ALNUM = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
ZIP5_GRID = tuple(f"{(i * 3607) % 100000:05d}" for i in range(12))
POSTCODE7_GRID = tuple(
    "".join(_ALNUM[(i * (j + 5) + 7) % len(_ALNUM)] for j in range(7))
    for i in range(12)
)
ZIP_GRID = ZIP5_GRID + POSTCODE7_GRID

# Regular dates plus leap days generated by formula.
DATE_GRID = tuple(
    (date(2019, 1, 1) + timedelta(days=i * 53)).isoformat() for i in range(12)
) + ("2024-02-29", "2020-02-29", "2000-02-29")


# --------------------------------------------------------------------------- #
# Specificity measurement for the monotonicity gate                           #
# --------------------------------------------------------------------------- #
def _age_specificity(label: str) -> float:
    """Coarseness of an age output: larger means coarser (less specific)."""
    if label == SUPPRESSED:
        return float("inf")
    if label == AGE_TOP_BAND:
        return float(AGE_MAX - AGE_TOP_THRESHOLD + 1)
    lower, upper = (int(part) for part in label.split("-"))
    return float(upper - lower + 1)


def _zip_specificity(label: str) -> float:
    """Coarseness of a ZIP output: fewer retained characters is coarser."""
    if label == SUPPRESSED:
        return float("inf")
    return float(-len(label))


def _date_specificity(label: str) -> float:
    """Coarseness of a date output by remaining granularity."""
    if label == SUPPRESSED:
        return 3.0
    granularity = label.count("-")  # day=2, month=1, year=0 dashes
    return float(2 - granularity)


_SPECIFICITY = {
    COLUMN_TYPE_AGE: _age_specificity,
    COLUMN_TYPE_ZIP: _zip_specificity,
    COLUMN_TYPE_DATE: _date_specificity,
}


def _generalize(column_type: str, value: object, level: int) -> str:
    kwargs = {}
    if column_type == COLUMN_TYPE_DATE:
        kwargs = {"patient_key": f"subject::{value}", "secret": SECRET}
    return generalize_value(column_type, value, level, **kwargs)


COLUMN_GRIDS = {
    COLUMN_TYPE_AGE: AGE_GRID,
    COLUMN_TYPE_ZIP: ZIP_GRID,
    COLUMN_TYPE_DATE: DATE_GRID,
}


# --------------------------------------------------------------------------- #
# Contract / metadata                                                         #
# --------------------------------------------------------------------------- #
def test_supported_column_types_are_registered():
    assert SUPPORTED_COLUMN_TYPES == {
        COLUMN_TYPE_AGE,
        COLUMN_TYPE_ZIP,
        COLUMN_TYPE_DATE,
    }


@pytest.mark.parametrize("column_type", sorted(SUPPORTED_COLUMN_TYPES))
def test_hierarchy_exposes_ordered_versioned_levels(column_type):
    hierarchy = get_hierarchy(column_type)
    assert isinstance(hierarchy, Hierarchy)
    assert hierarchy.column_type == column_type
    assert hierarchy.version == HIERARCHY_SCHEMA_VERSION
    assert hierarchy.max_level == max_level(column_type)
    assert len(hierarchy.levels) == hierarchy.max_level + 1
    # Levels are index-aligned and describe_level round-trips.
    for index, level in enumerate(hierarchy.levels):
        assert isinstance(level, GeneralizationLevel)
        assert level.level == index
        assert describe_level(column_type, index) == level
        assert level.key and level.description
    # The coarsest rung is full suppression.
    assert (
        hierarchy.apply(
            next(iter(COLUMN_GRIDS[column_type])),
            hierarchy.max_level,
            patient_key="k",
            secret=SECRET,
        )
        == SUPPRESSED
    )
    # Machine keys are unique per hierarchy.
    keys = [level.key for level in hierarchy.levels]
    assert len(keys) == len(set(keys))


def test_hierarchy_apply_matches_module_function():
    d = "2021-06-15"
    hierarchy = get_hierarchy(COLUMN_TYPE_DATE)
    for level in range(hierarchy.max_level + 1):
        via_method = hierarchy.apply(d, level, patient_key="subject-A", secret=SECRET)
        via_function = generalize_value(
            COLUMN_TYPE_DATE, d, level, patient_key="subject-A", secret=SECRET
        )
        assert via_method == via_function


# --------------------------------------------------------------------------- #
# Acceptance: monotonicity over the whole grid                                #
# --------------------------------------------------------------------------- #
@pytest.mark.parametrize("column_type", sorted(SUPPORTED_COLUMN_TYPES))
def test_monotone_non_increasing_specificity(column_type):
    """Level N+1 output is never more specific than level N (over a grid)."""
    specificity = _SPECIFICITY[column_type]
    top = max_level(column_type)
    for value in COLUMN_GRIDS[column_type]:
        previous = None
        for level in range(top + 1):
            output = _generalize(column_type, value, level)
            current = specificity(output)
            if previous is not None:
                assert current >= previous, (
                    f"{column_type} value {value!r} became more specific "
                    f"at level {level}: {output!r}"
                )
            previous = current


