def test_age_top_band_collapses_to_single_band():
    for age in (AGE_TOP_THRESHOLD, AGE_TOP_THRESHOLD + 1, 120, AGE_MAX):
        for level in range(len(get_hierarchy(COLUMN_TYPE_AGE).levels) - 1):
            assert generalize_value(COLUMN_TYPE_AGE, age, level) == AGE_TOP_BAND


def test_age_boundary_bands_at_finest_level():
    assert generalize_value(COLUMN_TYPE_AGE, 0, 0) == "0-4"
    assert generalize_value(COLUMN_TYPE_AGE, 89, 0) == "85-89"
    assert generalize_value(COLUMN_TYPE_AGE, 90, 0) == AGE_TOP_BAND
    assert generalize_value(COLUMN_TYPE_AGE, 120, 0) == AGE_TOP_BAND


def test_no_age_band_below_minimum_width_on_grid():
    """Quantitative gate: zero sub-minimum bands across the fixture grid."""
    band_re = re.compile(r"^(\d+)-(\d+)$")
    offenders = []
    top = max_level(COLUMN_TYPE_AGE)
    for age in AGE_GRID:
        for level in range(top + 1):
            output = generalize_value(COLUMN_TYPE_AGE, age, level)
            match = band_re.match(output)
            if not match:
                continue
            lower, upper = int(match.group(1)), int(match.group(2))
            if (upper - lower + 1) < AGE_MIN_BAND_WIDTH:
                offenders.append((age, level, output))
    assert offenders == []


def test_age_bands_nest_across_levels():
    # 45 -> 45-49 (5y) within 40-49 (10y) within 40-59 (20y).
    assert generalize_value(COLUMN_TYPE_AGE, 45, 0) == "45-49"
    assert generalize_value(COLUMN_TYPE_AGE, 45, 1) == "40-49"
    assert generalize_value(COLUMN_TYPE_AGE, 45, 2) == "40-59"


def test_age_accepts_digit_strings():
    assert generalize_value(COLUMN_TYPE_AGE, "45", 0) == "45-49"


