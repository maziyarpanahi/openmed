def test_zip_prefix_truncation_drops_trailing_characters():
    assert generalize_value(COLUMN_TYPE_ZIP, "02139", 0) == "02139"
    assert generalize_value(COLUMN_TYPE_ZIP, "02139", 1) == "0213"
    assert generalize_value(COLUMN_TYPE_ZIP, "02139", 2) == "021"
    assert generalize_value(COLUMN_TYPE_ZIP, "02139", 3) == "02"
    assert generalize_value(COLUMN_TYPE_ZIP, "02139", 4) == "0"
    assert generalize_value(COLUMN_TYPE_ZIP, "02139", 5) == SUPPRESSED


def test_zip_seven_char_postcode_reaches_suppression():
    postcode = "SW1A1AA"
    assert generalize_value(COLUMN_TYPE_ZIP, postcode, 0) == postcode
    assert generalize_value(COLUMN_TYPE_ZIP, postcode, 1) == "SW1A1A"
    assert generalize_value(COLUMN_TYPE_ZIP, postcode, max_level(COLUMN_TYPE_ZIP)) == (
        SUPPRESSED
    )


def test_zip_all_grid_values_fully_suppress_at_top():
    top = max_level(COLUMN_TYPE_ZIP)
    for value in ZIP_GRID:
        assert generalize_value(COLUMN_TYPE_ZIP, value, top) == SUPPRESSED


