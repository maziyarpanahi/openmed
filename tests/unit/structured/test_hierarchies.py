def test_date_shift_offset_is_stable_and_matches_core_helper():
    d = "2025-04-09"
    key = "patient-42"
    first = generalize_value(COLUMN_TYPE_DATE, d, 0, patient_key=key, secret=SECRET)
    second = generalize_value(COLUMN_TYPE_DATE, d, 0, patient_key=key, secret=SECRET)
    assert first == second
    offset = stable_offset_for(key, max_days=365, secret=SECRET)
    expected = (date(2025, 4, 9) + timedelta(days=offset)).isoformat()
    assert first == expected


def test_date_shift_preserves_interval_deltas():
    key = "patient-99"
    d1 = date(2025, 1, 1)
    d2 = date(2025, 3, 15)
    s1 = generalize_value(
        COLUMN_TYPE_DATE, d1.isoformat(), 0, patient_key=key, secret=SECRET
    )
    s2 = generalize_value(
        COLUMN_TYPE_DATE, d2.isoformat(), 0, patient_key=key, secret=SECRET
    )
    shifted1 = datetime.strptime(s1, "%Y-%m-%d").date()
    shifted2 = datetime.strptime(s2, "%Y-%m-%d").date()
    assert (shifted2 - shifted1) == (d2 - d1)


def test_date_truncation_drops_day_then_month():
    d = "2024-02-29"  # leap day
    assert generalize_value(COLUMN_TYPE_DATE, d, 1) == "2024-02"
    assert generalize_value(COLUMN_TYPE_DATE, d, 2) == "2024"
    assert (
        generalize_value(COLUMN_TYPE_DATE, d, max_level(COLUMN_TYPE_DATE)) == SUPPRESSED
    )


def test_date_shift_requires_patient_key_and_secret():
    with pytest.raises(HierarchyError):
        generalize_value(COLUMN_TYPE_DATE, "2025-01-01", 0)
    with pytest.raises(HierarchyError):
        generalize_value(COLUMN_TYPE_DATE, "2025-01-01", 0, patient_key="k")


