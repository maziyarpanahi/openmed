def test_adding_a_property_changes_output_and_fails_check(tmp_path: Path) -> None:
    def add(document: dict[str, Any]) -> None:
        document["properties"]["synthetic_count"] = {"type": "integer"}
        document["required"].append("synthetic_count")

    schema_dir = _schemas_with(tmp_path, "relation", add)
    relation = _class(
        emit_kotlin_types.render(contract_schema.load_contract_model(schema_dir)),
        "OpenMedContractRelation",
    )
    assert "    val syntheticCount: Int,\n" in relation
    assert '"synthetic_count"' in relation

    stale = _run("--check", "--schema-dir", str(schema_dir))
    assert stale.returncode == 1
    assert "contract/ContractTypes.kt" in stale.stderr
    assert "synthetic_count" not in stale.stderr

    output = tmp_path / "ContractTypes.kt"
    args = ("--schema-dir", str(schema_dir), "--output", str(output))
    assert _run(*args).returncode == 0
    assert _run("--check", *args).returncode == 0


def test_optional_property_defaults_to_null_and_is_omitted(tmp_path: Path) -> None:
    def add(document: dict[str, Any]) -> None:
        document["properties"]["synthetic_note"] = {"type": "string"}

    schema_dir = _schemas_with(tmp_path, "code", add)
    code = _class(
        emit_kotlin_types.render(contract_schema.load_contract_model(schema_dir)),
        "OpenMedContractCode",
    )

    assert "    val syntheticNote: String? = null,\n" in code
    assert 'syntheticNote?.let { fields["synthetic_note"] = JsonPrimitive(it) }' in code
    assert 'syntheticNote = json["synthetic_note"]?.let {' in code


