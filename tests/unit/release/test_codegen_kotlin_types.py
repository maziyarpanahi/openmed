def _load(name: str, path: Path) -> ModuleType:
    if str(CODEGEN_DIR) not in sys.path:
        sys.path.insert(0, str(CODEGEN_DIR))
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


contract_schema = _load("contract_schema", CODEGEN_DIR / "contract_schema.py")
emit_kotlin_types = _load("emit_kotlin_types", SCRIPT)


def _run(*args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(SCRIPT), *args],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )


def _schemas_with(tmp_path: Path, name: str, edit: Any) -> Path:
    target = tmp_path / "schemas"
    target.mkdir()
    for schema in contract_schema.CORE_SCHEMAS:
        file_name = contract_schema.schema_file_name(schema)
        shutil.copyfile(SCHEMA_DIR / file_name, target / file_name)
    path = target / contract_schema.schema_file_name(name)
    document = json.loads(path.read_text(encoding="utf-8"))
    edit(document)
    path.write_text(json.dumps(document, indent=2), encoding="utf-8")
    return target


def _class(source: str, name: str) -> str:
    start = source.index(f"data class {name}(\n")
    return source[start : source.index("\n}\n", start)]


def test_committed_kotlin_contract_types_are_current() -> None:
    result = _run("--check")

    assert result.returncode == 0, result.stderr
    assert GENERATED.read_text(encoding="utf-8") == emit_kotlin_types.render(
        contract_schema.load_contract_model()
    )


def test_generation_is_deterministic_and_covers_every_record() -> None:
    model = contract_schema.load_contract_model()
    source = emit_kotlin_types.render(model)

    assert source == emit_kotlin_types.render(contract_schema.load_contract_model())
    assert source.startswith("// Generated by scripts/codegen/emit_kotlin_types.py.")
    assert "\npackage com.openmed.openmedkit.contract\n" in source
    for record in model.records:
        block = _class(source, f"OpenMedContract{record.name}")
        assert "fun toJson(): JsonObject {" in block
        assert (
            f"fun fromJson(json: JsonObject): OpenMedContract{record.name} {{" in block
        )


def test_generated_types_live_in_their_own_package_and_need_no_plugin() -> None:
    source = GENERATED.read_text(encoding="utf-8")
    declared = re.findall(
        r"^(?:data class|enum class|class) (\w+)", source, re.MULTILINE
    )

    assert declared and len(declared) == len(set(declared))
    assert all(name.startswith("OpenMedContract") for name in declared)
    assert "@Serializable" not in source
    assert "kotlinx.serialization.json.Json" in source
    assert (
        "serialization"
        not in BUILD_FILE.read_text(encoding="utf-8")
        .split("plugins {", 1)[1]
        .split("}", 1)[0]
    )
    for path in KOTLIN_MAIN.rglob("*.kt"):
        if path != GENERATED:
            assert "package com.openmed.openmedkit.contract" not in path.read_text(
                encoding="utf-8"
            ), path.name


def test_nullable_required_fields_fail_closed_and_keep_explicit_nulls() -> None:
    span = _class(GENERATED.read_text(encoding="utf-8"), "OpenMedContractSpan")

    assert "    val score: Double?,\n" in span
    assert (
        'score = contractRequire(json, TYPE, "score").let { if (it is JsonNull) '
        'null else contractDouble(it, TYPE, "score") },' in span
    )
    assert 'fields["score"] = score?.let { JsonPrimitive(it) } ?: JsonNull' in span
    assert "contractRequireDeclaredKeys(json, KEYS, TYPE)" in span
    assert "json[" not in span


def test_constants_are_fixed_and_checked_on_decode() -> None:
    source = GENERATED.read_text(encoding="utf-8")
    span = _class(source, "OpenMedContractSpan")
    execution = _class(source, "OpenMedContractDataResidencyAttestationExecution")

    assert "val schemaVersion: Int get() = 1" in span
    assert "val schemaVersion: Int," not in span
    assert 'throw contractFailure(TYPE, "schema_version", "constant_mismatch")' in span
    assert "val hostLocal: Boolean get() = true" in execution


def test_failure_messages_are_value_free_codes() -> None:
    source = GENERATED.read_text(encoding="utf-8")
    messages = re.findall(r'OpenMedContractException\("([^"]*)"\)', source)
    codes = set(re.findall(r'contractFailure\(\w+, "[^"]+", "([a-z_]+)"\)', source))
    codes |= set(re.findall(r'contractFailure\(type, key, "([a-z_]+)"\)', source))

    assert messages == [
        "$type.$key: $code",
        "$type: malformed_json",
        "$type: expected_object",
        "$type has an undeclared property",
    ]
    assert codes == {
        "missing_required_key",
        "expected_string",
        "expected_integer",
        "expected_number",
        "expected_boolean",
        "expected_object",
        "expected_array",
        "unknown_enum_value",
        "constant_mismatch",
    }
    assert "error.message" not in source and "cause" not in source


