interface TokenizerSpec {
  vocab: string[];
  markers: string[];
  word_pattern: string;
  unk_token: string;
  cls_token: string;
  sep_token: string;
}

interface EncoderSpec {
  hidden_size: number;
  embeddings: number[][];
  projection: number[][];
  projection_bias: number[];
  logit_scale: number;
  logit_bias: number;
  label_token_id: number;
  separator_token_id: number;
  ignored_token_ids: number[];
}

interface RuntimeSettings {
  prompt: string | null;
  examples: { text: string; labels: string[] }[];
  score_levels: string[];
  prompt_first: boolean;
  max_length: number;
  fault: string | null;
}

class WordLevelTokenizer implements DecisionTokenizer {
  readonly #ids: Map<string, number>;
  readonly #pattern: RegExp;
  readonly #spec: TokenizerSpec;

  constructor(spec: TokenizerSpec) {
    this.#spec = spec;
    this.#ids = new Map(spec.vocab.map((token, index) => [token, index]));
    this.#pattern = new RegExp(spec.word_pattern, "g");
  }

  tokenToId(token: string): number | undefined {
    return this.#ids.get(token);
  }

  encode(text: string): number[] {
    const id = (token: string) => this.#ids.get(token) ?? this.#ids.get(this.#spec.unk_token)!;
    const result = [id(this.#spec.cls_token)];
    let rest = text;
    for (;;) {
      let next: { index: number; marker: string } | undefined;
      for (const marker of this.#spec.markers) {
        const index = rest.indexOf(marker);
        if (index >= 0 && (next === undefined || index < next.index)) {
          next = { index, marker };
        }
      }
      const piece = next === undefined ? rest : rest.slice(0, next.index);
      const lowered = piece.replace(/[A-Z]/g, (char) => char.toLowerCase());
      for (const match of lowered.matchAll(this.#pattern)) {
        result.push(id(match[0]));
      }
      if (next === undefined) {
        break;
      }
      result.push(id(next.marker));
      rest = rest.slice(next.index + next.marker.length);
    }
    result.push(id(this.#spec.sep_token));
    return result;
  }
}

function tinyLogits(spec: EncoderSpec, ids: number[], mask: number[]): number[] {
  const size = spec.hidden_size;
  const hidden = ids.map((token) =>
    Array.from({ length: size }, (_, column) => {
      let total = 0;
      for (let inner = 0; inner < size; inner += 1) {
        total += spec.embeddings[token]![inner]! * spec.projection[inner]![column]!;
      }
      return Math.tanh(total + spec.projection_bias[column]!);
    }),
  );
  const spans: number[][] = [];
  ids.forEach((token, position) => {
    if (mask[position] !== 1 || token !== spec.label_token_id) {
      return;
    }
    let end = position + 1;
    while (end < ids.length && ids[end] !== spec.label_token_id && ids[end] !== spec.separator_token_id) {
      end += 1;
    }
    spans.push(Array.from({ length: end - position }, (_, offset) => position + offset));
  });
  const inLabel = new Set(spans.flat());
  const context = ids
    .map((_, position) => position)
    .filter(
      (position) =>
        mask[position] === 1 &&
        !inLabel.has(position) &&
        !spec.ignored_token_ids.includes(ids[position]!),
    );
  const mean = (positions: number[]) => {
    const totals = new Array<number>(size).fill(0);
    for (const position of positions) {
      for (let column = 0; column < size; column += 1) {
        totals[column]! += hidden[position]![column]!;
      }
    }
    return positions.length === 0 ? totals : totals.map((value) => value / positions.length);
  };
  const text = mean(context);
  return spans.map((span) => {
    const label = mean(span.filter((position) => mask[position] === 1));
    let dot = 0;
    for (let column = 0; column < size; column += 1) {
      dot += label[column]! * text[column]!;
    }
    return spec.logit_scale * dot + spec.logit_bias;
  });
}

class FakeTensor implements OrtTensorLike {
  [key: string]: unknown;
  constructor(
    readonly type: string,
    readonly data: unknown,
    readonly dims: readonly number[],
  ) {}
}

const Tensor = FakeTensor as unknown as OrtTensorConstructor;

function tinySession(
  spec: EncoderSpec,
  fault: string | null,
): OrtInferenceSession & { calls: { ids: number[]; logits: number[] | null; type: string }[] } {
  const calls: { ids: number[]; logits: number[] | null; type: string }[] = [];
  return {
    calls,
    async run(feeds) {
      const inputIds = feeds.input_ids as FakeTensor;
      const attention = feeds.attention_mask as FakeTensor;
      assert.deepEqual(inputIds.dims, attention.dims);
      const ids = Array.from(inputIds.data as ArrayLike<bigint | number>, Number);
      const mask = Array.from(attention.data as ArrayLike<bigint | number>, Number);
      if (fault === "raise") {
        calls.push({ ids, logits: null, type: inputIds.type });
        throw new Error("synthetic encoder fault");
      }
      let logits = Float32Array.from(tinyLogits(spec, ids, mask));
      if (fault === "short") {
        logits = logits.slice(0, -1);
      }
      if (fault === "non_finite") {
        logits[0] = Number.NaN;
      }
      calls.push({
        ids,
        logits: fault === "non_finite" ? null : Array.from(logits),
        type: inputIds.type,
      });
      if (fault === "missing") {
        return {};
      }
      const dims = fault === "rank3" ? [1, 1, logits.length] : [1, logits.length];
      return { logits: new FakeTensor("float32", logits, dims) };
    },
  };
}

function configuration(settings: RuntimeSettings): GLiClassDecisionConfiguration {
  return {
    prompt: settings.prompt,
    examples: settings.examples,
    scoreLevels: settings.score_levels,
    promptFirst: settings.prompt_first,
    maxLength: settings.max_length,
  };
}

function assertClose(actual: unknown, expected: unknown, tolerance: number, path: string): void {
  if (typeof expected === "number") {
    assert.equal(typeof actual, "number", path);
    assert.ok(Math.abs((actual as number) - expected) <= tolerance, `${path}: ${String(actual)}`);
  } else if (Array.isArray(expected)) {
    assert.ok(Array.isArray(actual), path);
    assert.equal(actual.length, expected.length, path);
    expected.forEach((item, index) => assertClose(actual[index], item, tolerance, `${path}[${index}]`));
  } else if (expected !== null && typeof expected === "object") {
    assert.ok(actual !== null && typeof actual === "object" && !Array.isArray(actual), path);
    assert.deepEqual(Object.keys(actual as object).sort(), Object.keys(expected).sort(), path);
    for (const [key, value] of Object.entries(expected)) {
      assertClose((actual as Record<string, unknown>)[key], value, tolerance, `${path}.${key}`);
    }
  } else {
    assert.equal(actual, expected, path);
  }
}

const tokenizer = new WordLevelTokenizer(fixture.tokenizer);

test("fixture is the shared synthetic decision contract", () => {
  assert.equal(fixture.schema_version, "openmed.tests.decision_encoder_parity.v1");
  assert.equal(fixture.synthetic, true);
  assert.equal(fixture.decision_schema_version, DECISION_SCHEMA_VERSION);
  assert.ok(fixture.cases.length >= 28);
});

test("shared vectors match the Python reference through ONNX Runtime Web", async () => {
  for (const row of fixture.cases) {
    const settings = fixture.runtimes[row.runtime]!;
    const session = tinySession(fixture.encoder, settings.fault);
    const runtime = new EncoderDecisionRuntime({
      encoder: createOrtDecisionEncoder({ session, Tensor }),
      tokenizer,
      identity: fixture.backend,
      configuration: configuration(settings),
      ...(row.policy === null ? {} : { policy: row.policy }),
      ...(row.calibration_profiles === null ? {} : { calibrationProfiles: row.calibration_profiles }),
    });

    const result = await runtime.decide(JSON.stringify(row.request));
    assertClose(result, row.expected.result, fixture.tolerance.scores, row.id);
    assert.equal(result.autonomous_action, false, row.id);
    assert.equal(result.review.required, true, row.id);

    assert.equal(session.calls.length, row.expected.encoder_calls.length, row.id);
    row.expected.encoder_calls.forEach((call, index) => {
      const recorded = session.calls[index]!;
      assert.deepEqual(recorded.ids, call.input_ids, row.id);
      assert.equal(recorded.type, "int64", row.id);
      if (call.logits !== null && recorded.logits !== null) {
        assertClose(recorded.logits, call.logits, fixture.tolerance.logits, row.id);
      }
    });
  }
});

test("invalid requests fail with the shared error kinds", () => {
  assert.ok(fixture.invalid_requests.length >= 25);
  for (const row of fixture.invalid_requests) {
    assert.throws(
      () => parseDecisionRequest(JSON.stringify(row.request)),
      (error: unknown) => error instanceof DecisionRuntimeError && error.kind === row.error,
      row.id,
    );
  }
});

test("errors, requests and examples stay value-free", () => {
  const secret = "Synthetic secret patient phrase 4266";
  assert.throws(
    () => parseDecisionRequest({ mode: "fixed_choice", input_text: secret, options: [secret] }),
    (error: unknown) =>
      error instanceof DecisionRuntimeError &&
      error.reason === "options_invalid" &&
      !String(error).includes(secret) &&
      !error.message.includes(secret),
  );
  const request = parseDecisionRequest({
    mode: "boolean_choice",
    input_text: secret,
    options: ["yes", "no"],
  });
  assert.ok(!String(request).includes(secret));
  assert.ok(!JSON.stringify(request).includes(secret));
  assert.ok(!Object.values(request).some((value) => String(value).includes(secret)));
});

test("timeouts are typed failures", async () => {
  let now = 0;
  const runtime = new EncoderDecisionRuntime({
    encoder: createOrtDecisionEncoder({ session: tinySession(fixture.encoder, null), Tensor }),
    tokenizer,
    identity: { ...fixture.backend, runtime: "onnxruntime-web" },
    clock: () => (now += 10_000),
  });
  const result = await runtime.decide({
    mode: "fixed_choice",
    input_text: "Synthetic urgent note.",
    options: ["urgent", "routine"],
    timeout_ms: 100,
  });
  assert.equal(result.state, "failure");
  assert.equal(result.code, "backend_timeout");
  assert.deepEqual(result.option_scores, []);
  assert.equal(result.choice, null);
});

test("the ONNX Runtime Web adapter rejects unexpected outputs and loads locally", async () => {
  const ids = [2, 4, 3];
  const mask = [1, 1, 1];
  for (const [fault, reason] of [
    ["rank3", "encoder_output_invalid"],
    ["missing", "encoder_output_missing"],
  ] as const) {
    const encoder = createOrtDecisionEncoder({ session: tinySession(fixture.encoder, fault), Tensor });
    await assert.rejects(
      async () => encoder.logits(ids, mask),
      (error: unknown) => error instanceof DecisionEncoderError && error.reason === reason,
    );
  }
  const session = tinySession(fixture.encoder, null);
  const int32 = createOrtDecisionEncoder({ session, Tensor, inputType: "int32" });
  assert.equal((await int32.logits(ids, mask)).length, 1);
  assert.equal(session.calls[0]!.type, "int32");
  await assert.rejects(
    async () => int32.logits([2], []),
    (error: unknown) => error instanceof DecisionEncoderError && error.reason === "encoder_input_invalid",
  );

  const created: string[] = [];
  const runtime: OrtWebRuntime = {
    env: {},
    Tensor,
    InferenceSession: {
      create: (modelPath) => {
        created.push(modelPath);
        return tinySession(fixture.encoder, null);
      },
    },
  };
  const capabilities: OrtWebCapabilityProfile = {
    webgpu: false,
    wasm: true,
    wasmSimd: true,
    sharedArrayBuffer: false,
    crossOriginIsolated: false,
    hardwareConcurrency: 4,
  };
  const loaded = await loadOrtWebDecisionEncoder({
    modelPath: "/models/openmed/tiny-gliclass/model.onnx",
    assetPath: "/models/openmed/ort/",
    runtime,
    capabilities,
    cache: new Map(),
  });
  assert.deepEqual(created, ["/models/openmed/tiny-gliclass/model.onnx"]);
  assert.equal(loaded.backend.backend, "wasm-basic");
  assert.equal((await loaded.logits(ids, mask)).length, 1);
  await assert.rejects(
    loadOrtWebDecisionEncoder({
      modelPath: "https://example.invalid/model.onnx",
      assetPath: "/models/openmed/ort/",
      runtime,
      capabilities,
      cache: new Map(),
    }),
  );
});

test("configuration, identity, policy and profiles are validated", () => {
  const invalid = (error: unknown) =>
    error instanceof DecisionRuntimeError && error.kind === "invalid_configuration";
  const base = {
    encoder: createOrtDecisionEncoder({ session: tinySession(fixture.encoder, null), Tensor }),
    tokenizer,
    identity: fixture.backend,
  };
  for (const configuration of [
    { prompt: "Decide <<SEP>> now." },
    { scoreLevels: ["low", "LOW"] },
    { maxLength: 0 },
  ]) {
    assert.throws(() => new EncoderDecisionRuntime({ ...base, configuration }), invalid);
  }
  assert.throws(
    () =>
      new EncoderDecisionRuntime({
        ...base,
        identity: { ...fixture.backend, license_sha256: "a".repeat(64) },
      }),
    invalid,
  );
  assert.throws(
    () =>
      new EncoderDecisionRuntime({
        ...base,
        policy: { allowed_namespaces: [], allowed_purposes: ["quality"] },
      }),
    invalid,
  );
  assert.throws(() => validateDecisionCalibrationProfile({ calibration_id: "x" }), invalid);
  const profile = {
    calibration_id: "openmed.tests.profile",
    version: "1.0.0",
    method: "deterministic_margin",
    minimum_confidence: 0.5,
    minimum_margin: 0.6,
    multi_label_threshold: 0.5,
    in_domain_digest: `sha256:${"1".repeat(64)}`,
    out_of_domain_digest: `sha256:${"2".repeat(64)}`,
  };
  assert.throws(() => validateDecisionCalibrationProfile(profile), invalid);
  assert.deepEqual(
    validateDecisionCalibrationProfile({ ...profile, minimum_margin: 0.1 }),
    { ...profile, minimum_margin: 0.1 },
  );
  assert.equal(
    formatGLiClassInput("Text.", ["a", "b"], { prompt: "Classify." }),
    "<<LABEL>>a<<LABEL>>b<<SEP>>Classify.Text.",
  );
});
