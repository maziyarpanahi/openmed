/**
 * Replays `tests/fixtures/parity/decision_encoder_v1.json`, generated by the
 * Python GLiClass ONNX reference path over a tiny random encoder, through the
 * ONNX Runtime encoder adapter and the on-device decision runtime.
 */
class DecisionRuntimeParityTest {
    private val corpus: JsonObject by lazy {
        val stream = requireNotNull(javaClass.classLoader?.getResourceAsStream(FIXTURE)) {
            "shared $FIXTURE was not synced into Android test resources"
        }
        val values = stream.bufferedReader(Charsets.UTF_8).use { Json.parseToJsonElement(it.readText()) }
            .jsonObject
        assertEquals("openmed.tests.decision_encoder_parity.v1", values.string("schema_version"))
        assertEquals(JsonPrimitive(true), values["synthetic"])
        assertEquals(OpenMedDecision.SCHEMA_VERSION, values.string("decision_schema_version"))
        values
    }

    @Test
    fun sharedVectorsMatchThePythonReferenceThroughOnnxRuntime() {
        val tokenizer = WordLevelTokenizer(corpus.obj("tokenizer"))
        val spec = TinyEncoderSpec(corpus.obj("encoder"))
        val tolerance = corpus.obj("tolerance")
        val scoreTolerance = tolerance.number("scores")
        val logitTolerance = tolerance.number("logits")
        val backend = corpus.obj("backend")
        val identity = DecisionBackendIdentity(
            backendId = backend.string("backend_id"),
            runtime = backend.string("runtime"),
            modelId = backend.string("model_id"),
            revision = backend.string("revision"),
            licenseId = backend.string("license_id"),
        )
        val runtimes = corpus.obj("runtimes")
        val cases = corpus["cases"]!!.jsonArray
        assertTrue(cases.size >= 28)

        for (entry in cases) {
            val row = entry.jsonObject
            val id = row.string("id")
            val settings = runtimes.obj(row.string("runtime"))
            val session = TinyOnnxSession(spec, settings["fault"].nullableString())
            val runtime = EncoderDecisionRuntime(
                encoder = OnnxDecisionEncoder(null, session),
                tokenizer = tokenizer,
                identity = identity,
                configuration = configuration(settings),
                policy = policy(row["policy"]),
                calibrationProfiles = profiles(row["calibration_profiles"]),
            )

            val result = runtime.decide(row["request"]!!.toString())
            val expected = row.obj("expected")
            assertClose(result.toJson(), expected["result"]!!, scoreTolerance, id)
            assertFalse(result.autonomousAction, id)
            assertTrue(result.reviewRequired, id)

            val calls = expected["encoder_calls"]!!.jsonArray
            assertEquals(calls.size, session.calls.size, id)
            calls.zip(session.calls).forEach { (call, recorded) ->
                val values = call.jsonObject
                assertEquals(
                    values["input_ids"]!!.jsonArray.map { it.jsonPrimitive.int },
                    recorded.first.toList(),
                    id,
                )
                val logits = values["logits"]
                if (logits != null && logits != JsonNull && recorded.second != null) {
                    assertClose(
                        JsonArray(recorded.second!!.map { JsonPrimitive(it) }),
                        logits,
                        logitTolerance,
                        id,
                    )
                }
            }
        }
    }

    @Test
    fun invalidRequestsFailWithTheSharedErrorKinds() {
        val rows = corpus["invalid_requests"]!!.jsonArray
        assertTrue(rows.size >= 25)
        for (entry in rows) {
            val row = entry.jsonObject
            val error = assertFailsWith<DecisionRuntimeError>(row.string("id")) {
                DecisionRequest.parse(row["request"]!!.toString())
            }
            assertEquals(row.string("error"), error.kind, row.string("id"))
        }
    }

    @Test
    fun errorsAndDescriptionsAreValueFree() {
        val secret = "Synthetic secret patient phrase 4266"
        val error = assertFailsWith<DecisionRuntimeError> {
            DecisionRequest.parse(
                """{"mode":"fixed_choice","input_text":"$secret","options":["$secret"]}""",
            )
        }
        assertFalse(error.toString().contains(secret))
        assertFalse(error.message.orEmpty().contains(secret))
        assertEquals("options_invalid", error.reason)
        val request = DecisionRequest.of(DecisionMode.BOOLEAN_CHOICE, secret, listOf("yes", "no"))
        assertFalse(request.toString().contains(secret))
        assertFalse(GLiClassExample(secret, listOf("yes")).toString().contains(secret))
    }

    @Test
    fun timeoutsAreTypedFailures() {
        var now = 0L
        val runtime = EncoderDecisionRuntime(
            encoder = OnnxDecisionEncoder(null, TinyOnnxSession(TinyEncoderSpec(corpus.obj("encoder")), null)),
            tokenizer = WordLevelTokenizer(corpus.obj("tokenizer")),
            identity = DecisionBackendIdentity(
                "openmed.tests.tiny", "onnxruntime-android", "openmed/tiny", "1.0.0", "Apache-2.0",
            ),
            clock = {
                now += 10_000_000_000L
                now
            },
        )
        val request = DecisionRequest.of(
            DecisionMode.FIXED_CHOICE,
            "Synthetic urgent note.",
            listOf("urgent", "routine"),
            timeoutMs = 100,
        )
        val result = runtime.decide(request)
        assertEquals(DecisionState.FAILURE, result.state)
        assertEquals("backend_timeout", result.code)
        assertTrue(result.optionScores.isEmpty())
        assertNull(result.choice)
    }

    @Test
    fun onnxAdapterRejectsUnexpectedGraphsAndOutputs() {
        val spec = TinyEncoderSpec(corpus.obj("encoder"))
        assertFailsWith<DecisionRuntimeError.InvalidConfiguration> {
            OnnxDecisionEncoder(null, TinyOnnxSession(spec, null, setOf("input_ids")))
        }
        val rank1 = OnnxDecisionEncoder(null, TinyOnnxSession(spec, "rank1"))
        assertEquals(
            "encoder_output_invalid",
            assertFailsWith<DecisionEncoderException> { rank1.logits(intArrayOf(2, 4, 3), intArrayOf(1, 1, 1)) }
                .reason,
        )
        val missing = OnnxDecisionEncoder(null, TinyOnnxSession(spec, "missing"))
        assertEquals(
            "encoder_output_missing",
            assertFailsWith<DecisionEncoderException> { missing.logits(intArrayOf(2, 4, 3), intArrayOf(1, 1, 1)) }
                .reason,
        )
        val session = TinyOnnxSession(spec, null)
        val int32 = OnnxDecisionEncoder(null, session, TensorElementType.INT32)
        int32.logits(intArrayOf(2, 4, 3), intArrayOf(1, 1, 1))
        assertEquals(TensorElementType.INT32, session.lastType)
        assertEquals(listOf(1L, 3L), session.lastShape)
        assertFailsWith<DecisionEncoderException> { int32.logits(intArrayOf(2), intArrayOf()) }
        int32.close()
        assertTrue(session.closed)
    }

    @Test
    fun configurationIsValidated() {
        assertFailsWith<DecisionRuntimeError.InvalidConfiguration> {
            GLiClassDecisionConfiguration(prompt = "Decide <<SEP>> now.")
        }
        assertFailsWith<DecisionRuntimeError.InvalidConfiguration> {
            GLiClassDecisionConfiguration(scoreLevels = listOf("low", "LOW"))
        }
        assertFailsWith<DecisionRuntimeError.InvalidConfiguration> {
            GLiClassDecisionConfiguration(maxLength = 0)
        }
        assertFailsWith<DecisionRuntimeError.InvalidConfiguration> {
            DecisionBackendIdentity("b", "onnx", "m", "1.0.0", "Apache-2.0", "a".repeat(64))
        }
        assertFailsWith<DecisionRuntimeError.InvalidConfiguration> {
            DecisionAccessPolicy(emptySet(), setOf("quality"))
        }
        assertFailsWith<DecisionRuntimeError.InvalidConfiguration> {
            DecisionCalibrationProfile.fromJson("""{"calibration_id":"x"}""")
        }
        val profile = DecisionCalibrationProfile(
            "openmed.tests.profile", "1.0.0", "deterministic_margin", 0.5, 0.1, 0.5,
            "sha256:" + "1".repeat(64), "sha256:" + "2".repeat(64),
        )
        assertEquals(profile, DecisionCalibrationProfile.fromJson(profile.toJson().toString()))
        val prompted = GLiClassDecisionConfiguration(prompt = "Classify.")
        assertEquals(71, prompted.promptDigest?.length)
        assertEquals(
            "<<LABEL>>a<<LABEL>>b<<SEP>>Classify.Text.",
            prompted.formatInput("Text.", listOf("a", "b")),
        )
    }

    private fun configuration(settings: JsonObject): GLiClassDecisionConfiguration =
        GLiClassDecisionConfiguration(
            prompt = settings["prompt"].nullableString(),
            examples = settings["examples"]!!.jsonArray.map {
                val example = it.jsonObject
                val labels = example["labels"]!!.jsonArray.map { label -> label.jsonPrimitive.content }
                GLiClassExample(example.string("text"), labels)
            },
            scoreLevels = settings["score_levels"]!!.jsonArray.map { it.jsonPrimitive.content },
            promptFirst = settings["prompt_first"]!!.jsonPrimitive.content.toBoolean(),
            maxLength = settings["max_length"]!!.jsonPrimitive.int,
        )

    private fun policy(value: JsonElement?): DecisionAccessPolicy {
        if (value == null || value == JsonNull) return DecisionAccessPolicy.STANDARD
        val fields = value.jsonObject
        fun strings(key: String) = fields[key]!!.jsonArray.map { it.jsonPrimitive.content }.toSet()
        return DecisionAccessPolicy(
            strings("allowed_namespaces"),
            strings("allowed_purposes"),
            strings("allowed_backend_kinds"),
            fields.string("policy_version"),
        )
    }

    private fun profiles(value: JsonElement?): List<DecisionCalibrationProfile> {
        if (value == null || value == JsonNull) return listOf(DecisionCalibrationProfile.STANDARD)
        return value.jsonArray.map { DecisionCalibrationProfile.fromJson(it.toString()) }
    }

    private fun assertClose(actual: JsonElement, expected: JsonElement, tolerance: Double, path: String) {
        when {
            expected is JsonObject -> {
                assertTrue(actual is JsonObject, path)
                assertEquals(expected.keys, actual.keys, path)
                expected.forEach { (key, value) -> assertClose(actual[key]!!, value, tolerance, "$path.$key") }
            }
            expected is JsonArray -> {
                assertTrue(actual is JsonArray, path)
                assertEquals(expected.size, actual.size, path)
                expected.indices.forEach { assertClose(actual[it], expected[it], tolerance, "$path[$it]") }
            }
            expected is JsonPrimitive && expected !is JsonNull && !expected.isString &&
                expected.content != "true" && expected.content != "false" -> {
                val number = (actual as? JsonPrimitive)?.takeIf { it !is JsonNull }?.content?.toDoubleOrNull()
                    ?: throw AssertionError("$path is not a number")
                assertTrue(abs(number - expected.content.toDouble()) <= tolerance, "$path: $number")
            }
            else -> assertEquals(expected, actual, path)
        }
    }

    private companion object {
        const val FIXTURE = "decision_encoder_v1.json"
    }
}

private fun JsonObject.obj(key: String): JsonObject = this[key]!!.jsonObject

private fun JsonObject.string(key: String): String = this[key]!!.jsonPrimitive.content

private fun JsonObject.number(key: String): Double = this[key]!!.jsonPrimitive.content.toDouble()

private fun JsonElement?.nullableString(): String? =
    if (this == null || this == JsonNull) null else jsonPrimitive.content

/** The fixture's word-level tokenizer: markers, ASCII lowercasing, one word pattern. */
private class WordLevelTokenizer(spec: JsonObject) : DecisionTokenizer {
    private val ids = spec["vocab"]!!.jsonArray.withIndex().associate { (index, token) ->
        token.jsonPrimitive.content to index
    }
    private val markers = spec["markers"]!!.jsonArray.map { it.jsonPrimitive.content }
    private val pattern = Regex(spec.string("word_pattern"))
    private val unknown = ids.getValue(spec.string("unk_token"))
    private val classification = ids.getValue(spec.string("cls_token"))
    private val separator = ids.getValue(spec.string("sep_token"))

    override fun tokenId(token: String): Int? = ids[token]

    override fun encode(text: String): IntArray {
        val result = mutableListOf(classification)
        var rest = text
        while (true) {
            val next = markers.mapNotNull { marker ->
                rest.indexOf(marker).takeIf { it >= 0 }?.let { it to marker }
            }.minByOrNull { it.first }
            appendWords(if (next == null) rest else rest.substring(0, next.first), result)
            if (next == null) break
            result.add(ids.getValue(next.second))
            rest = rest.substring(next.first + next.second.length)
        }
        result.add(separator)
        return result.toIntArray()
    }

    private fun appendWords(piece: String, result: MutableList<Int>) {
        val lowered = piece.map { if (it in 'A'..'Z') it + 32 else it }.joinToString("")
        pattern.findAll(lowered).forEach { result.add(ids[it.value] ?: unknown) }
    }
}

/** The fixture's tiny GLiClass-style encoder, in Float64. */
private class TinyEncoderSpec(spec: JsonObject) {
    private fun matrix(key: String, spec: JsonObject) =
        spec[key]!!.jsonArray.map { row -> row.jsonArray.map { it.jsonPrimitive.content.toDouble() } }

    private val embeddings = matrix("embeddings", spec)
    private val projection = matrix("projection", spec)
    private val bias = spec["projection_bias"]!!.jsonArray.map { it.jsonPrimitive.content.toDouble() }
    private val size = spec["hidden_size"]!!.jsonPrimitive.int
    private val scale = spec.number("logit_scale")
    private val logitBias = spec.number("logit_bias")
    private val labelId = spec["label_token_id"]!!.jsonPrimitive.int
    private val separatorId = spec["separator_token_id"]!!.jsonPrimitive.int
    private val ignored = spec["ignored_token_ids"]!!.jsonArray.map { it.jsonPrimitive.int }.toSet()

    fun logits(ids: IntArray, mask: IntArray): DoubleArray {
        val hidden = ids.map { token ->
            DoubleArray(size) { column ->
                var total = 0.0
                for (inner in 0 until size) total += embeddings[token][inner] * projection[inner][column]
                tanh(total + bias[column])
            }
        }
        val spans = mutableListOf<IntRange>()
        for (position in ids.indices) {
            if (mask[position] != 1 || ids[position] != labelId) continue
            var end = position + 1
            while (end < ids.size && ids[end] != labelId && ids[end] != separatorId) end += 1
            spans.add(position until end)
        }
        val inLabel = spans.flatMap { it.toList() }.toSet()
        val context = ids.indices.filter { mask[it] == 1 && it !in inLabel && ids[it] !in ignored }
        fun mean(positions: List<Int>): DoubleArray {
            val totals = DoubleArray(size)
            for (position in positions) {
                for (column in 0 until size) totals[column] += hidden[position][column]
            }
            return if (positions.isEmpty()) totals else DoubleArray(size) { totals[it] / positions.size }
        }
        val text = mean(context)
        return DoubleArray(spans.size) { index ->
            val label = mean(spans[index].filter { mask[it] == 1 })
            var dot = 0.0
            for (column in 0 until size) dot += label[column] * text[column]
            scale * dot + logitBias
        }
    }
}

/** An ONNX Runtime-shaped session that runs the tiny encoder with float32 output. */
private class TinyOnnxSession(
    private val spec: TinyEncoderSpec,
    private val fault: String?,
    override val inputNames: Set<String> = setOf("input_ids", "attention_mask"),
) : TokenClassificationSession {
    val calls = mutableListOf<Pair<IntArray, DoubleArray?>>()
    var lastType: TensorElementType? = null
    var lastShape: List<Long>? = null
    var closed = false

    override fun run(inputs: Map<String, TokenInputTensor>): Map<String, Any?> {
        val ids = inputs.getValue("input_ids")
        val mask = inputs.getValue("attention_mask")
        lastType = ids.elementType
        lastShape = ids.shape.toList()
        assertEquals(ids.shape.toList(), mask.shape.toList())
        if (fault == "raise") {
            calls.add(ids.values to null)
            throw IllegalStateException("synthetic encoder fault")
        }
        var logits = spec.logits(ids.values, mask.values).map { it.toFloat() }.toFloatArray()
        if (fault == "short") logits = logits.copyOf(logits.size - 1)
        if (fault == "non_finite") logits[0] = Float.NaN
        val recorded = if (fault == "non_finite") null else DoubleArray(logits.size) { logits[it].toDouble() }
        calls.add(ids.values to recorded)
        return when (fault) {
            "missing" -> emptyMap()
            "rank1" -> mapOf("logits" to logits)
            else -> mapOf("logits" to arrayOf(logits))
        }
    }

    override fun close() {
        closed = true
    }
}
