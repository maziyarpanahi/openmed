#!/usr/bin/env python3
"""Render the environment-variable reference page from the settings schema.

The page ``docs/configuration/environment-variables.md`` is generated from
``openmed/core/settings.schema.json`` through
:mod:`openmed.core.settings_registry`, grouped by schema section.  Every row
lists the variable, its description, type, default, bounds, secret flag and
owning module.  Secret settings render as "secret, no default"; no default is
ever printed for them.

Usage::

    python scripts/docs/render_settings_reference.py          # rewrite the page
    python scripts/docs/render_settings_reference.py --check  # fail on drift

``--check`` exits with status 1 when the committed page differs from a fresh
render, which is how the docs publication tests catch a schema edit that was
not followed by regeneration.  The renderer reads only the schema; it never
reads the process environment.
"""

from __future__ import annotations

import argparse
import html
import json
import re
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from openmed.core.settings_registry import (  # noqa: E402
    SettingDeclaration,
    SettingsSection,
    load_settings_schema,
    parse_excluded_identifiers,
    parse_settings_schema,
    settings_schema_path,
)

DEFAULT_OUTPUT = ROOT / "docs" / "configuration" / "environment-variables.md"
SECRET_DEFAULT = "secret, no default"
USER_SUPPLIED_DEFAULT = "user-supplied, no default"
NO_DEFAULT = "no default"
UNSET = "unset"
EMPTY = "empty"
NO_BOUNDS = "-"

_FORMAT_LABELS = {
    "byte-size": "byte size",
    "csv": "comma-separated",
    "duration": "duration",
    "json": "JSON",
    "path": "path",
    "url": "URL",
}
_SETTING_NAME_RE = re.compile(r"\b((?:OPENMED|HF|XDG)_[A-Z0-9_]*[A-Z0-9])\b")
_TABLE_HEADER = (
    "| Variable | Description | Type | Default | Bounds | Secret | Module |\n"
    "| --- | --- | --- | --- | --- | --- | --- |\n"
)
_INTRO = """\
# Environment variables

<!-- Generated by scripts/docs/render_settings_reference.py from
openmed/core/settings.schema.json. Do not edit by hand: change the schema, then
run `python scripts/docs/render_settings_reference.py`. -->

This page lists every environment variable declared in
`openmed/core/settings.schema.json`, grouped by schema section. It is generated
from the schema, and the docs tests fail when the two drift apart.

Each row gives the type of the parsed value, the default that applies when the
variable is unset, its bounds, whether it holds a secret, and the module that
owns it. Notes on reading the table:

- **Secret** settings never show a default. Prefer the matching `*_FILE`
  setting, which names a mounted secret file, where one is listed.
- **user-supplied** settings point at data you provide, such as an evaluation
  dataset. They have no default, and OpenMed never downloads or bundles the
  data.
- **unset** means the variable has no value by default and the owning module
  falls back to the behavior described in the row.
- **comma-separated** values are lists such as `a,b,c`; **JSON** values are a
  JSON document; **byte size** values accept a byte count or a size such as
  `512MiB`; **duration** values accept seconds or a duration such as `5m`.

The declarations come from `openmed.core.settings_registry`, which never reads
the environment. See [Configuration & Validation](../configuration.md) for how
`OpenMedConfig` is loaded and
[Configuration Precedence Audit](precedence-audit.md) for value-free provenance
reports.
"""


def render_reference(
    sections: Sequence[SettingsSection],
    excluded: Mapping[str, str] | None = None,
) -> str:
    """Render the reference page for ``sections``.

    Args:
        sections: Parsed settings sections, in schema order.
        excluded: ``OPENMED_*`` identifiers that are not settings, with the
            reason for each; rendered after the sections when present.

    Returns:
        The Markdown page, ending with one newline.
    """

    parts = [_INTRO]
    for section in sections:
        parts.append(f"\n## {_text(section.title)}\n\n")
        if section.description:
            parts.append(f"{_text(section.description)}\n\n")
        count = len(section.settings)
        noun = "setting" if count == 1 else "settings"
        parts.append(f"{count} {noun}.\n\n")
        parts.append(_TABLE_HEADER)
        parts.extend(_row(setting) for setting in section.settings)
    if excluded:
        parts.append(_EXCLUDED_INTRO)
        parts.extend(
            f"| {_code(name)} | {_text(reason)} |\n"
            for name, reason in sorted(excluded.items())
        )
    return "".join(parts)


_EXCLUDED_INTRO = """
## Identifiers that are not settings

These `OPENMED_*` identifiers appear in the code but are not environment
settings: constants such as FHIR system names and error codes, or names OpenMed
exports to a subprocess. Setting them in the environment has no effect.

| Identifier | Reason |
| --- | --- |
"""


def render_schema(schema_path: Path | None = None) -> str:
    """Render the reference page from a settings schema file.

    Args:
        schema_path: Schema to render; defaults to the installed schema.

    Returns:
        The Markdown page.
    """

    if schema_path is None:
        document = load_settings_schema()
    else:
        document = json.loads(schema_path.read_text(encoding="utf-8"))
    return render_reference(
        parse_settings_schema(document), parse_excluded_identifiers(document)
    )


def check_reference(output: Path, rendered: str) -> list[str]:
    """Return drift problems between ``output`` and a fresh render.

    Args:
        output: Committed reference page.
        rendered: Freshly rendered page.

    Returns:
        Human-readable problems; empty when the page is current.
    """

    if not output.is_file():
        return [f"{_display(output)} is missing"]
    committed = output.read_text(encoding="utf-8")
    if committed == rendered:
        return []
    committed_lines = committed.splitlines()
    rendered_lines = rendered.splitlines()
    for index, (left, right) in enumerate(zip(committed_lines, rendered_lines)):
        if left != right:
            return [f"{_display(output)} is stale from line {index + 1}"]
    return [f"{_display(output)} is stale: its length differs from a fresh render"]


def main(argv: Sequence[str] | None = None) -> int:
    """Render or check the environment-variable reference page.

    Args:
        argv: Command-line arguments; defaults to ``sys.argv[1:]``.

    Returns:
        Process exit status: 0 on success, 1 when ``--check`` finds drift.
    """

    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail instead of writing when the committed page is stale",
    )
    parser.add_argument(
        "--schema",
        type=Path,
        default=None,
        help=f"settings schema to render (default: {_display(settings_schema_path())})",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help=f"page to write or check (default: {_display(DEFAULT_OUTPUT)})",
    )
    args = parser.parse_args(argv)
    rendered = render_schema(args.schema)

    if args.check:
        problems = check_reference(args.output, rendered)
        for problem in problems:
            print(problem, file=sys.stderr)
        if problems:
            print(
                "Regenerate with: python scripts/docs/render_settings_reference.py",
                file=sys.stderr,
            )
            return 1
        print(f"{_display(args.output)} is current")
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered, encoding="utf-8")
    print(f"wrote {_display(args.output)}")
    return 0


def _row(setting: SettingDeclaration) -> str:
    description = _text(setting.description)
    if setting.default_note and not setting.secret:
        description += f" Default: {_text(setting.default_note)}"
    cells = (
        _code(setting.name),
        description,
        _type_label(setting),
        _default_label(setting),
        _bounds_label(setting),
        "yes" if setting.secret else "no",
        _code(setting.module),
    )
    return "| " + " | ".join(cells) + " |\n"


def _type_label(setting: SettingDeclaration) -> str:
    types = [
        "list" if item == "array" and setting.env_format == "csv" else item
        for item in setting.types
        if item != "null"
    ]
    label = " or ".join(types) if types else "null"
    if setting.env_format is not None:
        label += f" ({_FORMAT_LABELS[setting.env_format]})"
    return label


def _default_label(setting: SettingDeclaration) -> str:
    # A secret never shows a default, even if a malformed schema carried one.
    if setting.secret:
        return SECRET_DEFAULT
    if setting.user_supplied:
        return USER_SUPPLIED_DEFAULT
    if not setting.has_default:
        return NO_DEFAULT
    return _value(setting.default)


def _value(value: Any) -> str:
    if value is None:
        return UNSET
    if isinstance(value, bool):
        return _code("true" if value else "false")
    if isinstance(value, (tuple, list)):
        if not value:
            return EMPTY
        return _code(",".join(str(item) for item in value))
    if isinstance(value, float) and value.is_integer():
        return _code(f"{value:.1f}")
    return _code(str(value))


def _bounds_label(setting: SettingDeclaration) -> str:
    bounds = setting.bounds
    parts: list[str] = []
    if "enum" in bounds:
        choices = [item for item in bounds["enum"] if item is not None]
        parts.append("one of " + ", ".join(_code(str(item)) for item in choices))
    for keyword, label in (
        ("minimum", "minimum"),
        ("exclusiveMinimum", "above"),
        ("maximum", "maximum"),
        ("exclusiveMaximum", "below"),
    ):
        if keyword in bounds:
            parts.append(f"{label} {_number(bounds[keyword])}")
    if "minLength" in bounds:
        parts.append(f"at least {_characters(bounds['minLength'])}")
    if "maxLength" in bounds:
        parts.append(f"at most {_characters(bounds['maxLength'])}")
    if "pattern" in bounds:
        parts.append("matches " + _code(str(bounds["pattern"])))
    return "; ".join(parts) if parts else NO_BOUNDS


def _characters(count: int) -> str:
    return f"{count} character" if count == 1 else f"{count} characters"


def _number(value: Any) -> str:
    if isinstance(value, float) and value.is_integer():
        value = int(value)
    if isinstance(value, int) and abs(value) >= 10_000:
        return f"{value:,}"
    return str(value)


def _code(text: str) -> str:
    """Return ``text`` as inline code that is safe inside a Markdown table."""

    if "`" not in text and "|" not in text:
        return f"`{text}`"
    escaped = "".join(_ENTITIES.get(char, char) for char in text)
    return f"<code>{escaped}</code>"


_ENTITIES = {
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    "|": "&#124;",
    "`": "&#96;",
    "*": "&#42;",
    "_": "&#95;",
    "\\": "&#92;",
    "[": "&#91;",
    "]": "&#93;",
}


def _text(text: str) -> str:
    """Escape prose for a table cell and set setting names in code."""

    pieces = _SETTING_NAME_RE.split(text)
    rendered: list[str] = []
    for index, piece in enumerate(pieces):
        if index % 2:
            rendered.append(f"`{piece}`")
            continue
        piece = html.escape(piece, quote=False)
        piece = piece.replace("|", "&#124;").replace("*", "&#42;")
        rendered.append(piece.replace("_", "&#95;"))
    return "".join(rendered)


def _display(path: Path) -> str:
    try:
        return path.resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return path.name


if __name__ == "__main__":
    raise SystemExit(main())
