#!/usr/bin/env python3
"""Generate TypeScript contract types from the canonical JSON Schemas.

Writes ``js/openmedkit-web/src/generated/contract-types.ts`` from the eight core
schemas in ``openmed/core/schemas/json/``: one ``OpenMedContract*`` interface per
record (nested objects get their own interface) and the canonical label, policy
label and span action lists as ``as const`` arrays. The output is types and
constant arrays only, so it adds no runtime dependency.

``python scripts/codegen/emit_ts_types.py`` rewrites the file;
``--check`` fails without writing when the committed file has drifted.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

from contract_schema import (  # noqa: E402
    CORE_SCHEMAS,
    ROOT,
    ContractModel,
    Field,
    NamedEnum,
    Record,
    TypeRef,
    run_emitter,
)

SCRIPT = "scripts/codegen/emit_ts_types.py"
OUTPUT = ROOT / "js" / "openmedkit-web" / "src" / "generated" / "contract-types.ts"
TYPE_PREFIX = "OpenMedContract"
_IDENTIFIER = frozenset(
    "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_$"
)


def render(model: ContractModel) -> str:
    """Return the full text of the generated TypeScript module.

    Args:
        model: Lowered core contract schemas.

    Returns:
        Module source ending with a newline.
    """
    sources = ",".join(CORE_SCHEMAS)
    lines = [
        f"// Generated by {SCRIPT}. Do not edit by hand.",
        f"// Source: openmed/core/schemas/json/{{{sources}}}.schema.json",
        f"// Schema digest: {model.digest}",
        f"// Regenerate with `python {SCRIPT}`; CI runs it with `--check`.",
    ]
    for named in model.enums:
        lines.append("")
        lines.extend(_enum_lines(named))
    for record in model.records:
        lines.append("")
        lines.extend(_record_lines(record))
    return "\n".join(lines) + "\n"


def type_name(record_name: str) -> str:
    """Return the exported TypeScript name of a lowered record."""
    return TYPE_PREFIX + record_name


def _enum_lines(named: NamedEnum) -> list[str]:
    spec = named.spec
    source = f"{spec.schema}.schema.json #/properties/{spec.property}"
    lines = [f"/** Values of `{source}`, in schema order. */"]
    lines.append(f"export const {spec.constant_name} = [")
    lines.extend(f"  {json.dumps(value)}," for value in named.values)
    lines.append("] as const;")
    lines.append("")
    lines.append(
        f"export type {spec.type_name} = (typeof {spec.constant_name})[number];"
    )
    return lines


def _record_lines(record: Record) -> list[str]:
    if record.title is not None:
        summary = (
            f"`{record.title}` from `{record.source}`, schema version "
            f"{record.schema_version}."
        )
    else:
        summary = f"Nested object `{record.source}`."
    lines = [f"/** {summary} */", f"export interface {type_name(record.name)} {{"]
    for field in record.fields:
        lines.extend(_field_lines(field))
    lines.append("}")
    return lines


def _field_lines(field: Field) -> list[str]:
    lines: list[str] = []
    note = _constraint_note(field.type)
    if note:
        lines.append(f"  /** {note} */")
    key = field.name if _is_identifier(field.name) else json.dumps(field.name)
    optional = "" if field.required else "?"
    lines.append(f"  {key}{optional}: {_ts_type(field.type)};")
    return lines


def _ts_type(ref: TypeRef) -> str:
    base = _ts_base(ref)
    return f"{base} | null" if ref.nullable else base


def _ts_base(ref: TypeRef) -> str:
    if ref.const is not None:
        return json.dumps(ref.const)
    if ref.kind == "string":
        if ref.string_prefix:
            return f"`{_template_text(ref.string_prefix)}${{string}}`"
        return "string"
    if ref.kind in {"integer", "number"}:
        return "number"
    if ref.kind == "boolean":
        return "boolean"
    if ref.kind == "enum":
        assert ref.enum is not None
        if ref.enum.name is not None:
            return ref.enum.name.type_name
        return " | ".join(json.dumps(value) for value in ref.enum.values)
    if ref.kind == "record":
        assert ref.record is not None
        return type_name(ref.record)
    if ref.kind == "json_object":
        return "Record<string, unknown>"
    if ref.kind == "array":
        assert ref.items is not None
        item = _ts_type(ref.items)
        simple = all(char in _IDENTIFIER for char in item)
        return f"{item}[]" if simple else f"Array<{item}>"
    raise AssertionError(f"unhandled kind {ref.kind}")


def _constraint_note(ref: TypeRef) -> str:
    parts = [
        f"{keyword} {json.dumps(value, ensure_ascii=False)}"
        for keyword, value in ref.constraints
    ]
    text = "; ".join(parts)
    return text.replace("*/", "*\\/")


def _template_text(text: str) -> str:
    return text.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")


def _is_identifier(name: str) -> bool:
    return bool(name) and not name[0].isdigit() and all(c in _IDENTIFIER for c in name)


def main(argv: list[str] | None = None) -> int:
    """Generate or ``--check`` the TypeScript contract types."""
    return run_emitter(
        description=__doc__ or "",
        script=SCRIPT,
        default_output=OUTPUT,
        render=render,
        argv=argv,
    )


if __name__ == "__main__":
    raise SystemExit(main())
