#!/usr/bin/env python3
"""Generate and verify the kit error-code enums from the error-code registry.

``openmed/core/error_codes.json`` is the single source of truth. This script
renders the registry's ``portable`` codes, the codes a client kit can raise,
into one small typed enum per kit:

* ``swift/OpenMedKit/Sources/OpenMedKit/Generated/OpenMedErrorCode.swift``,
* ``android/openmedkit/src/main/kotlin/com/openmed/openmedkit/OpenMedErrorCode.kt``,
* ``js/openmedkit-web/src/error-codes.ts``.

Each enum carries only the stable wire code and the registry's retryable
flag. The files are not wired into any kit behaviour; kit adoption is
separate work. Output is deterministic: codes are sorted and nothing depends
on the clock, locale or host.

Run without arguments to rewrite the files, or with ``--check`` to fail when a
committed file differs from the registry. Messages name files only.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from openmed.core.error_registry import (  # noqa: E402
    ErrorCodeEntry,
    ErrorCodeRegistry,
    load_error_registry,
)

SWIFT_PATH = Path(
    "swift/OpenMedKit/Sources/OpenMedKit/Generated/OpenMedErrorCode.swift"
)
KOTLIN_PATH = Path(
    "android/openmedkit/src/main/kotlin/com/openmed/openmedkit/OpenMedErrorCode.kt"
)
TYPESCRIPT_PATH = Path("js/openmedkit-web/src/error-codes.ts")
UPDATE_COMMAND = "python scripts/generate_error_code_enums.py"


def _header(comment: str, registry: ErrorCodeRegistry) -> str:
    return (
        f"{comment} Generated by scripts/generate_error_code_enums.py from\n"
        f"{comment} openmed/core/error_codes.json (contract version "
        f"{registry.contract_version}).\n"
        f"{comment} Do not edit: change the registry and regenerate.\n"
    )


def _camel(code: str) -> str:
    head, *rest = code.split("_")
    return head + "".join(part.title() for part in rest)


def _portable(registry: ErrorCodeRegistry) -> Sequence[ErrorCodeEntry]:
    entries = registry.portable_codes()
    if not entries:
        raise SystemExit("The error-code registry declares no portable codes")
    return entries


def render_swift(registry: ErrorCodeRegistry) -> str:
    """Return the Swift ``OpenMedErrorCode`` source."""
    lines = [
        _header("//", registry),
        "/// Portable OpenMed error codes shared by every runtime.",
        "///",
        "/// The raw value is the stable wire code from the OpenMed error-code",
        "/// registry. `isRetryable` says whether retrying the unchanged request",
        "/// may succeed.",
        "public enum OpenMedErrorCode: String, CaseIterable, Sendable {",
    ]
    entries = _portable(registry)
    for entry in entries:
        lines.append(f"    /// {entry.description}")
        lines.append(f'    case {_camel(entry.code)} = "{entry.code}"')
    lines += [
        "",
        "    /// Whether retrying the unchanged request may succeed.",
        "    public var isRetryable: Bool {",
        "        switch self {",
    ]
    for flag in (True, False):
        cases = ", ".join(
            f".{_camel(entry.code)}" for entry in entries if entry.retryable is flag
        )
        if cases:
            lines.append(f"        case {cases}:")
            lines.append(f"            return {'true' if flag else 'false'}")
    lines += ["        }", "    }", "}", ""]
    return "\n".join(lines)


def render_kotlin(registry: ErrorCodeRegistry) -> str:
    """Return the Kotlin ``OpenMedErrorCode`` source."""
    lines = [
        _header("//", registry),
        "package com.openmed.openmedkit",
        "",
        "/**",
        " * Portable OpenMed error codes shared by every runtime.",
        " *",
        " * [code] is the stable wire code from the OpenMed error-code registry;",
        " * [retryable] says whether retrying the unchanged request may succeed.",
        " */",
        "enum class OpenMedErrorCode(val code: String, val retryable: Boolean) {",
    ]
    for entry in _portable(registry):
        flag = "true" if entry.retryable else "false"
        lines.append(f"    /** {entry.description} */")
        lines.append(f'    {entry.code.upper()}("{entry.code}", {flag}),')
    lines += ["}", ""]
    return "\n".join(lines)


def render_typescript(registry: ErrorCodeRegistry) -> str:
    """Return the TypeScript error-code module source."""
    entries = _portable(registry)
    lines = [
        _header("//", registry),
        "/**",
        " * Portable OpenMed error codes shared by every runtime, keyed by name.",
        " * Each value is the stable wire code from the OpenMed error-code registry.",
        " */",
        "export const OPENMED_ERROR_CODES = Object.freeze({",
    ]
    for entry in entries:
        lines.append(f"  /** {entry.description} */")
        lines.append(f'  {_camel(entry.code)}: "{entry.code}",')
    lines += [
        "} as const);",
        "",
        "/** A portable OpenMed error code. */",
        "export type OpenMedErrorCode =",
        "  (typeof OPENMED_ERROR_CODES)[keyof typeof OPENMED_ERROR_CODES];",
        "",
        "/** Whether retrying the unchanged request may succeed, per code. */",
        "export const OPENMED_ERROR_CODE_RETRYABLE: Readonly<",
        "  Record<OpenMedErrorCode, boolean>",
        "> = Object.freeze({",
    ]
    for entry in entries:
        flag = "true" if entry.retryable else "false"
        lines.append(f"  {entry.code}: {flag},")
    lines += ["});", ""]
    return "\n".join(lines)


def render_all(registry: ErrorCodeRegistry) -> Mapping[Path, str]:
    """Return every generated file keyed by its repository-relative path."""
    return {
        SWIFT_PATH: render_swift(registry),
        KOTLIN_PATH: render_kotlin(registry),
        TYPESCRIPT_PATH: render_typescript(registry),
    }


def stale_files(root: Path = ROOT) -> list[str]:
    """Return the generated files that differ from the registry."""
    stale: list[str] = []
    for relative, text in render_all(load_error_registry()).items():
        path = root / relative
        try:
            current = path.read_text(encoding="utf-8")
        except FileNotFoundError:
            current = None
        if current != text:
            stale.append(relative.as_posix())
    return stale


def main(argv: Sequence[str] | None = None) -> int:
    """Write or check the generated kit enums.

    Args:
        argv: Command-line arguments; ``--check`` verifies instead of writing.

    Returns:
        ``0`` on success, ``1`` when ``--check`` finds a stale file.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if a committed enum differs from the error-code registry",
    )
    args = parser.parse_args(argv)
    if args.check:
        stale = stale_files()
        if stale:
            print(
                "Generated error-code enums are out of date; run "
                f"`{UPDATE_COMMAND}` and commit the result. Drift: " + ", ".join(stale),
                file=sys.stderr,
            )
            return 1
        return 0
    for relative, text in render_all(load_error_registry()).items():
        path = ROOT / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
