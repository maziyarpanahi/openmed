#!/usr/bin/env python3
"""Write the shipped-classpath view of Gradle lockfiles for vulnerability scans.

A ``gradle.lockfile`` pins every resolvable configuration of a module: the
release runtime classpath, but also unit-test classpaths, the Kotlin compiler
and coverage tooling. Trivy reads every entry and cannot tell those apart, so
the OpenMedKit lockfile scan gates the release runtime view: the dependencies
an AAR consumer or a release APK actually receives. This matches Trivy's
default for npm and Cargo lockfiles, which already skips development-only
dependencies. Test and tooling entries stay locked and checksum-verified.

Each ``*gradle.lockfile`` under ``--source`` is copied to the same relative path
under ``--output`` with only the entries resolved on ``--configuration``. The
script prints counts only and fails closed, without echoing lockfile content,
when no lockfile or no shipped entry is found or a line is malformed.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import NoReturn

LOCKFILE_SUFFIX = "gradle.lockfile"
DEFAULT_CONFIGURATION = "releaseRuntimeClasspath"
SKIPPED_DIRECTORIES = frozenset({".gradle", ".kotlin", "build"})
MAX_LOCKFILES = 256
MAX_LOCKFILE_BYTES = 4 * 1024 * 1024
HEADER = (
    "# Release runtime view generated by scripts/security/gradle_lockfile_view.py\n"
    "# for vulnerability scanning. Do not commit this file.\n"
)
COORDINATE = r"[A-Za-z0-9][A-Za-z0-9._-]{0,199}"
VERSION = r"[A-Za-z0-9][A-Za-z0-9.+_-]{0,199}"
CONFIGURATIONS = r"[A-Za-z0-9_-]+(?:,[A-Za-z0-9_-]+)*"
ENTRY_PATTERN = re.compile(
    rf"(?P<module>{COORDINATE}:{COORDINATE}):(?P<version>{VERSION})"
    rf"=(?P<configurations>{CONFIGURATIONS})"
)
EMPTY_PATTERN = re.compile(rf"empty=(?:{CONFIGURATIONS})?")
CONFIGURATION_PATTERN = re.compile(r"[A-Za-z][A-Za-z0-9_]{0,199}")


class ViewError(Exception):
    """A value-free failure code for an invalid lockfile view request."""


@dataclass(frozen=True)
class ViewSummary:
    """Counts describing one generated lockfile view."""

    lockfiles: int
    entries: int


class ViewArgumentParser(argparse.ArgumentParser):
    """Keep malformed CLI diagnostics free of caller-provided values."""

    def error(self, message: str) -> NoReturn:
        self.exit(2, "gradle lockfile view failed: invalid_cli_arguments\n")


def find_lockfiles(source: Path) -> list[Path]:
    """Return Gradle lockfiles under ``source``, skipping build output folders.

    Args:
        source: Directory that contains one or more Gradle modules.

    Returns:
        Lockfile paths sorted by their path relative to ``source``.

    Raises:
        ViewError: If ``source`` is not a directory or holds too many lockfiles.
    """
    if not source.is_dir():
        raise ViewError("source_not_a_directory")
    lockfiles = []
    for path in sorted(source.rglob(f"*{LOCKFILE_SUFFIX}")):
        relative = path.relative_to(source)
        if SKIPPED_DIRECTORIES.intersection(relative.parts[:-1]):
            continue
        if not path.is_file() or path.is_symlink():
            raise ViewError("lockfile_not_a_regular_file")
        lockfiles.append(path)
        if len(lockfiles) > MAX_LOCKFILES:
            raise ViewError("too_many_lockfiles")
    return lockfiles


def shipped_entries(text: str, configuration: str) -> list[str]:
    """Return lockfile entries resolved on ``configuration``.

    Args:
        text: Contents of one ``gradle.lockfile``.
        configuration: Configuration whose entries are kept.

    Returns:
        The kept ``group:artifact:version=configurations`` lines, in file order.

    Raises:
        ViewError: If a non-comment line is not a Gradle lock entry.
    """
    kept = []
    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        if EMPTY_PATTERN.fullmatch(line):
            continue
        match = ENTRY_PATTERN.fullmatch(line)
        if match is None:
            raise ViewError("malformed_lockfile_entry")
        if configuration in match.group("configurations").split(","):
            kept.append(f"{match.group('module')}:{match.group('version')}")
    return kept


def write_view(source: Path, output: Path, configuration: str) -> ViewSummary:
    """Write the ``configuration`` view of every lockfile under ``source``.

    Args:
        source: Directory that contains the committed Gradle lockfiles.
        output: Empty or missing directory that receives the views.
        configuration: Configuration whose entries are kept.

    Returns:
        Counts of lockfiles found and entries written.

    Raises:
        ViewError: If inputs are invalid or no shipped entry is found.
    """
    if CONFIGURATION_PATTERN.fullmatch(configuration) is None:
        raise ViewError("invalid_configuration_name")
    source = source.resolve()
    output = output.resolve()
    if output == source or source in output.parents or output in source.parents:
        raise ViewError("output_overlaps_source")
    if output.exists() and (not output.is_dir() or any(output.iterdir())):
        raise ViewError("output_not_empty")
    lockfiles = find_lockfiles(source)
    if not lockfiles:
        raise ViewError("no_gradle_lockfiles")

    views: dict[Path, list[str]] = {}
    for path in lockfiles:
        raw = path.read_bytes()
        if len(raw) > MAX_LOCKFILE_BYTES:
            raise ViewError("lockfile_too_large")
        try:
            text = raw.decode("utf-8")
        except UnicodeDecodeError:
            raise ViewError("lockfile_not_utf8") from None
        entries = shipped_entries(text, configuration)
        if entries:
            views[path.relative_to(source)] = entries
    total = sum(len(entries) for entries in views.values())
    if total == 0:
        raise ViewError("no_shipped_entries")

    for relative, entries in views.items():
        target = output / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        lines = [f"{entry}={configuration}\n" for entry in entries]
        target.write_text(HEADER + "".join(lines), encoding="utf-8")
    return ViewSummary(lockfiles=len(lockfiles), entries=total)


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    """Parse command-line arguments."""
    parser = ViewArgumentParser(description=__doc__)
    parser.add_argument(
        "--source",
        type=Path,
        required=True,
        help="Directory containing committed Gradle lockfiles (for example android).",
    )
    parser.add_argument(
        "--output",
        type=Path,
        required=True,
        help="Empty directory that receives the scan views.",
    )
    parser.add_argument(
        "--configuration",
        default=DEFAULT_CONFIGURATION,
        help="Configuration whose entries are kept.",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    """Run the lockfile view command."""
    args = parse_args(argv)
    try:
        summary = write_view(args.source, args.output, args.configuration)
    except ViewError as exc:
        print(f"gradle lockfile view failed: {exc}", file=sys.stderr)
        return 1
    except OSError:
        print("gradle lockfile view failed: io_error", file=sys.stderr)
        return 1
    print(
        "gradle lockfile view written: "
        f"{summary.lockfiles} lockfiles, {summary.entries} shipped entries"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
