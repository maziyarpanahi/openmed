#!/usr/bin/env python3
"""Generate or check the portable policy resources shipped by every kit.

``openmed/core/policies/``, ``openmed/core/labels.py``, and
``openmed/core/thresholds.json`` are the single source of truth.
:mod:`openmed.core.portable_policy` lowers them into versioned canonical JSON
(``openmed.portable_policy`` version 1); this script writes the exact same
bytes into:

* ``swift/OpenMedKit/Sources/OpenMedKit/Resources/policies/`` (SwiftPM),
* ``android/openmedkit/src/main/assets/policies/`` (Android assets),
* ``js/openmedkit-web/src/portable-policy-resources.ts`` (TypeScript module
  embedding the same documents), and
* ``js/openmedkit-react-native/src/portable-taxonomy-labels.ts`` (the
  taxonomy label list the React Native kit-parity validator uses).

It also derives the expected outputs of the shared decision vectors in
``tests/fixtures/parity/portable_policy_vectors.json`` from the Python
reference engine.

``--check`` (the default) fails with value-free reason codes and file names
when any generated file or vector expectation is stale. ``--write`` refreshes
them in place; review the diff and run every kit's policy tests afterwards.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from openmed.core import portable_policy as portable  # noqa: E402

SWIFT_DIR = ROOT / "swift/OpenMedKit/Sources/OpenMedKit/Resources/policies"
ANDROID_DIR = ROOT / "android/openmedkit/src/main/assets/policies"
WEB_MODULE = ROOT / "js/openmedkit-web/src/portable-policy-resources.ts"
RN_LABELS_MODULE = ROOT / "js/openmedkit-react-native/src/portable-taxonomy-labels.ts"
VECTORS_PATH = "tests/fixtures/parity/portable_policy_vectors.json"
VECTORS_FILE = ROOT / VECTORS_PATH
VECTORS_SCHEMA = "openmed.portable_policy_vectors"
VECTORS_VERSION = 1
UPDATE_COMMAND = "python scripts/parity/generate_portable_policies.py --write"

_HEADER = (
    "// Generated by scripts/parity/generate_portable_policies.py --write.\n"
    "// Do not edit: change openmed/core/policies/ and regenerate.\n"
)

#: Kit consumers that must pass whenever the resources or vectors change.
CONSUMERS: tuple[Mapping[str, str], ...] = (
    {
        "surface": "python",
        "test": "tests/unit/parity/test_portable_policy.py",
        "gate": "pytest",
    },
    {
        "surface": "swift",
        "test": "swift/OpenMedKit/Tests/OpenMedKitTests/PortablePolicyVectorTests.swift",
        "gate": "swift test --filter PortablePolicyVectorTests",
    },
    {
        "surface": "kotlin",
        "test": (
            "android/openmedkit/src/test/kotlin/com/openmed/openmedkit/policy/"
            "PortablePolicyVectorTest.kt"
        ),
        "gate": "--tests '*PortablePolicyVectorTest'",
    },
    {
        "surface": "web",
        "test": "tests/web/test_portable_policy.spec.ts",
        "gate": "npm --prefix js/openmedkit-web test",
    },
)


class GenerationError(Exception):
    """A value-free generator failure."""

    def __init__(self, code: str, *, target: str = "", case_id: str = "") -> None:
        self.code = code
        self.target = target
        self.case_id = case_id
        parts = [code]
        if target:
            parts.append(f"target={target}")
        if case_id:
            parts.append(f"case={case_id}")
        super().__init__(" ".join(parts))


def _template_literal(text: str) -> str:
    if "\\" in text or "`" in text or "${" in text:
        raise GenerationError("resource_not_template_safe")
    return f"`{text}`"


def web_module(files: Mapping[str, bytes]) -> str:
    """Return the generated TypeScript resource module."""
    taxonomy = json.loads(files[portable.TAXONOMY_FILE].decode("ascii"))
    lines = [_HEADER, "/** Portable policy resources, byte-identical to every kit. */"]
    lines.append(
        "export const PORTABLE_POLICY_RESOURCES: Readonly<Record<string, string>> ="
    )
    lines.append("  Object.freeze({")
    for name, data in files.items():
        lines.append(
            f"    {json.dumps(name)}: {_template_literal(data.decode('ascii'))},"
        )
    lines.append("  });")
    lines.append("")
    lines.append(_labels_literal(taxonomy))
    return "\n".join(lines)


def rn_labels_module(files: Mapping[str, bytes]) -> str:
    """Return the generated React Native taxonomy label module."""
    taxonomy = json.loads(files[portable.TAXONOMY_FILE].decode("ascii"))
    return "\n".join((_HEADER, _labels_literal(taxonomy)))


def _labels_literal(taxonomy: Mapping[str, Any]) -> str:
    labels = sorted(taxonomy["labels"])
    body = "\n".join(f"  {json.dumps(label)}," for label in labels)
    return (
        "/** Canonical labels of the portable policy taxonomy, sorted. */\n"
        f"export const PORTABLE_TAXONOMY_LABELS: readonly string[] = [\n{body}\n];\n"
    )


def expected_targets(files: Mapping[str, bytes]) -> dict[Path, bytes]:
    """Return every generated file path with its expected bytes."""
    targets: dict[Path, bytes] = {}
    for directory in (SWIFT_DIR, ANDROID_DIR):
        for name, data in files.items():
            targets[directory / name] = data
    targets[WEB_MODULE] = web_module(files).encode("utf-8")
    targets[RN_LABELS_MODULE] = rn_labels_module(files).encode("utf-8")
    return targets


def _display(path: Path) -> str:
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return path.name


def _stale_resource_files(targets: Mapping[Path, bytes]) -> list[Path]:
    stale: list[Path] = []
    for directory in (SWIFT_DIR, ANDROID_DIR):
        if not directory.is_dir():
            continue
        for path in sorted(directory.glob("*.json")):
            if path not in targets:
                stale.append(path)
    return stale


# ---------------------------------------------------------------------------
# Decision vectors
# ---------------------------------------------------------------------------


def _detections(raw: Sequence[Mapping[str, Any]]) -> list[portable.PortableDetection]:
    return [
        portable.PortableDetection(
            label=item["label"],
            start=item["start"],
            end=item["end"],
            confidence_ppm=item["confidence_ppm"],
            source=item.get("source", "model"),
            validated=item.get("validated", True),
        )
        for item in raw
    ]


def _key(vectors: Mapping[str, Any], case: Mapping[str, Any]) -> bytes | None:
    name = case.get("surrogate_key")
    if name is None:
        return None
    return bytes.fromhex(vectors["surrogate_test_keys"][name])


def derive_decision(
    vectors: Mapping[str, Any],
    case: Mapping[str, Any],
    files: Mapping[str, bytes],
) -> dict[str, Any]:
    """Run the Python reference engine for one decision case."""
    policy = portable.load_portable_policy(case["profile"], resource_files=files)
    outcome = portable.decide(
        policy,
        case["text"],
        _detections(case["detections"]),
        overrides=case.get("overrides"),
        surrogate_key=_key(vectors, case),
    )
    result_json = portable.kit_parity.serialize_result(outcome.result)
    return {
        "decisions": [decision.to_dict() for decision in outcome.decisions],
        "deidentified_text": outcome.result.deidentified_text,
        "policy_digest": outcome.policy_digest,
        "result_json": result_json,
        "result_sha256": hashlib.sha256(result_json.encode("utf-8")).hexdigest(),
    }


def derive_error(
    vectors: Mapping[str, Any],
    case: Mapping[str, Any],
    files: Mapping[str, bytes],
) -> dict[str, str]:
    """Run the Python reference engine for one error case."""
    policy = portable.load_portable_policy(case["profile"], resource_files=files)
    try:
        portable.decide(
            policy,
            case["text"],
            _detections(case["detections"]),
            overrides=case.get("overrides"),
            surrogate_key=_key(vectors, case),
        )
    except portable.PortablePolicyError as error:
        return {"code": error.code, "field_path": error.field_path}
    raise GenerationError("error_case_accepted", case_id=case["id"])


def patched_files(
    case: Mapping[str, Any], files: Mapping[str, bytes]
) -> tuple[dict[str, bytes], dict[str, Any] | None]:
    """Apply a load case's manifest patch; return files and a profile patch."""
    patched = dict(files)
    manifest_patch = case.get("manifest_patch")
    if manifest_patch:
        manifest = json.loads(patched[portable.MANIFEST_FILE].decode("ascii"))
        for field, value in manifest_patch.items():
            if isinstance(value, dict) and isinstance(manifest.get(field), dict):
                manifest[field] = {**manifest[field], **value}
            else:
                manifest[field] = value
        patched[portable.MANIFEST_FILE] = json.dumps(manifest).encode("ascii")
    return patched, case.get("profile_patch")


def run_load_case(
    case: Mapping[str, Any], files: Mapping[str, bytes]
) -> portable.PortablePolicy:
    """Execute one load case the way every kit's test does."""
    patched, profile_patch = patched_files(case, files)
    if profile_patch is None:
        return portable.load_portable_policy(
            case["profile"],
            expected_digest=case.get("expected_digest"),
            resource_files=patched,
        )
    policy = portable.load_portable_policy(case["profile"], resource_files=patched)
    document = {**policy.document, **profile_patch}
    return portable.decode_profile(
        document, name=policy.name, digest=policy.digest, taxonomy=policy.taxonomy
    )


def derive_load(case: Mapping[str, Any], files: Mapping[str, bytes]) -> dict[str, Any]:
    """Return the expected outcome of one load case."""
    try:
        policy = run_load_case(case, files)
    except portable.PortablePolicyError as error:
        return {"code": error.code, "field_path": error.field_path}
    return {
        "digest": policy.digest,
        "name": policy.name,
        "required_capabilities": list(policy.required_capabilities),
    }


def derive_vectors(
    vectors: Mapping[str, Any], files: Mapping[str, bytes]
) -> dict[str, Any]:
    """Return the vectors document with every derived field recomputed."""
    derived = json.loads(json.dumps(vectors))
    manifest = json.loads(files[portable.MANIFEST_FILE].decode("ascii"))
    derived["ir"] = {"schema": portable.IR_SCHEMA, "version": portable.IR_VERSION}
    derived["manifest_sha256"] = hashlib.sha256(
        files[portable.MANIFEST_FILE]
    ).hexdigest()
    derived["profiles"] = manifest["profiles"]
    derived["excluded_profiles"] = manifest["excluded_profiles"]
    derived["taxonomy_digest"] = manifest["taxonomy_digest"]
    derived["supported_capabilities"] = list(portable.SUPPORTED_CAPABILITIES)
    derived["consumers"] = [dict(item) for item in CONSUMERS]
    for case in derived["decision_cases"]:
        case["expected"] = derive_decision(derived, case, files)
    for case in derived["error_cases"]:
        case["expected"] = derive_error(derived, case, files)
    for case in derived["load_cases"]:
        case["expected"] = derive_load(case, files)
    return derived


def validate_vectors(vectors: Mapping[str, Any]) -> None:
    """Validate the hand-authored structure of the vectors document."""
    if vectors.get("schema") != VECTORS_SCHEMA:
        raise GenerationError("vectors_schema_invalid", target=VECTORS_PATH)
    if vectors.get("version") != VECTORS_VERSION:
        raise GenerationError("vectors_version_invalid", target=VECTORS_PATH)
    seen: set[str] = set()
    for group in ("decision_cases", "error_cases", "load_cases"):
        for case in vectors.get(group) or ():
            case_id = case.get("id")
            if not isinstance(case_id, str) or case_id in seen:
                raise GenerationError("vector_id_invalid", target=VECTORS_PATH)
            seen.add(case_id)
    for name, value in (vectors.get("surrogate_test_keys") or {}).items():
        if not name.startswith("synthetic_test_key_"):
            raise GenerationError("surrogate_key_name_invalid", target=VECTORS_PATH)
        bytes.fromhex(value)


def vectors_bytes(document: Mapping[str, Any]) -> bytes:
    """Serialize the vectors document deterministically."""
    text = json.dumps(document, indent=2, ensure_ascii=False, sort_keys=False)
    return (text + "\n").encode("utf-8")


# ---------------------------------------------------------------------------
# Entry points
# ---------------------------------------------------------------------------


def check(root_files: Mapping[str, bytes] | None = None) -> list[str]:
    """Return value-free staleness problems (empty when everything is current)."""
    files = dict(root_files or portable.build_resources())
    problems: list[str] = []
    targets = expected_targets(files)
    for path, data in targets.items():
        relative = _display(path)
        if not path.is_file():
            problems.append(f"resource_missing target={relative}")
        elif path.read_bytes() != data:
            problems.append(f"resource_stale target={relative}")
    for path in _stale_resource_files(targets):
        problems.append(f"resource_unexpected target={_display(path)}")
    if not VECTORS_FILE.is_file():
        problems.append(f"vectors_missing target={VECTORS_PATH}")
        return problems
    current = json.loads(VECTORS_FILE.read_text(encoding="utf-8"))
    try:
        validate_vectors(current)
        derived = derive_vectors(current, files)
    except (GenerationError, portable.PortablePolicyError, KeyError) as error:
        problems.append(f"vectors_invalid target={VECTORS_PATH} reason={error}")
        return problems
    if vectors_bytes(derived) != VECTORS_FILE.read_bytes():
        problems.append(f"vectors_stale target={VECTORS_PATH}")
    return problems


def write() -> None:
    """Regenerate every resource and the derived vector expectations."""
    files = portable.build_resources()
    targets = expected_targets(files)
    for path in _stale_resource_files(targets):
        path.unlink()
    for path, data in targets.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    current = json.loads(VECTORS_FILE.read_text(encoding="utf-8"))
    validate_vectors(current)
    VECTORS_FILE.write_bytes(vectors_bytes(derive_vectors(current, files)))


def main(argv: Sequence[str] | None = None) -> int:
    """Run the generator; ``--check`` is the default."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail when stale")
    mode.add_argument("--write", action="store_true", help="regenerate in place")
    args = parser.parse_args(argv)
    if args.write:
        write()
        return 0
    problems = check()
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        print(f"refresh with: {UPDATE_COMMAND}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
