#!/usr/bin/env node
// Render, check or update the committed .d.ts API baseline of @openmed/rest-client.
//
// The baseline is the declaration output of `tsc -p tsconfig.json`, emitted in
// memory, re-printed without comments and concatenated in file-name order, so a
// doc-comment edit never changes it but any change to an exported name, field,
// parameter or type does. It includes the generated Journey workflow types.
//
//   node scripts/api-baseline.mjs --check   # exit 1 when the baseline is stale
//   node scripts/api-baseline.mjs --update  # rewrite api/rest-client.api.d.ts

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import ts from "typescript";

export const PACKAGE_DIR = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const BASELINE_PATH = join(PACKAGE_DIR, "api", "rest-client.api.d.ts");
const UPDATE_COMMAND = "npm run api:update";
const HEADER = [
  "// Public API baseline of @openmed/rest-client.",
  "// Generated by scripts/api-baseline.mjs from the tsc declaration output; do not edit.",
  `// Review every change, then refresh it with \`${UPDATE_COMMAND}\`.`,
  "",
].join("\n");

/**
 * Render the normalized declaration baseline.
 *
 * @param {{ overrides?: Record<string, string> }} [options] Source text to use
 *   instead of the file on disk, keyed by a path relative to the package.
 * @returns {string} The baseline text.
 */
export function renderApi({ overrides = {} } = {}) {
  const configPath = join(PACKAGE_DIR, "tsconfig.json");
  const config = ts.readConfigFile(configPath, ts.sys.readFile);
  if (config.error !== undefined) {
    throw new Error("api_baseline_tsconfig_unreadable");
  }
  const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, PACKAGE_DIR);
  const outDir = parsed.options.outDir ?? join(PACKAGE_DIR, "dist");
  const options = {
    ...parsed.options,
    declaration: true,
    declarationMap: false,
    emitDeclarationOnly: true,
    noEmit: false,
    outDir,
    sourceMap: false,
  };
  const replaced = new Map(
    Object.entries(overrides).map(([path, text]) => [resolve(PACKAGE_DIR, path), text]),
  );
  const host = ts.createCompilerHost(options, true);
  const readSourceFile = host.getSourceFile.bind(host);
  host.getSourceFile = (fileName, languageVersion, onError, shouldCreate) => {
    const text = replaced.get(resolve(fileName));
    if (text !== undefined) {
      return ts.createSourceFile(fileName, text, languageVersion, true);
    }
    return readSourceFile(fileName, languageVersion, onError, shouldCreate);
  };

  const program = ts.createProgram(parsed.fileNames, options, host);
  const errors = ts
    .getPreEmitDiagnostics(program)
    .filter((item) => item.category === ts.DiagnosticCategory.Error);
  if (errors.length > 0) {
    throw new Error(`api_baseline_type_errors count=${errors.length}`);
  }
  const declarations = new Map();
  const result = program.emit(
    undefined,
    (fileName, text) => {
      if (fileName.endsWith(".d.ts")) {
        declarations.set(relative(outDir, fileName).split(sep).join("/"), text);
      }
    },
    undefined,
    true,
  );
  if (result.emitSkipped || declarations.size === 0) {
    throw new Error("api_baseline_emit_failed");
  }

  const printer = ts.createPrinter({
    newLine: ts.NewLineKind.LineFeed,
    removeComments: true,
  });
  const sections = [...declarations.keys()].sort().map((name) => {
    const source = ts.createSourceFile(
      name,
      declarations.get(name),
      ts.ScriptTarget.Latest,
      false,
      ts.ScriptKind.TS,
    );
    const printed = printer
      .printFile(source)
      .split("\n")
      .map((line) => line.trimEnd())
      .join("\n")
      .trim();
    return `// ${name}\n${printed}\n`;
  });
  return `${HEADER}\n${sections.join("\n")}`;
}

/**
 * Compare the committed baseline with a fresh render.
 *
 * @param {string} rendered Freshly rendered baseline.
 * @returns {{ ok: boolean, line: number | null }} The first differing line.
 */
export function compareApi(rendered) {
  const committed = existsSync(BASELINE_PATH) ? readFileSync(BASELINE_PATH, "utf8") : "";
  if (committed === rendered) {
    return { ok: true, line: null };
  }
  const left = committed.split("\n");
  const right = rendered.split("\n");
  const index = right.findIndex((line, position) => left[position] !== line);
  return { ok: false, line: (index === -1 ? right.length : index) + 1 };
}

function main(argv) {
  const mode = argv[0];
  if (mode !== "--check" && mode !== "--update") {
    console.error("usage: node scripts/api-baseline.mjs --check | --update");
    return 2;
  }
  const rendered = renderApi();
  const baseline = relative(PACKAGE_DIR, BASELINE_PATH).split(sep).join("/");
  if (mode === "--update") {
    mkdirSync(dirname(BASELINE_PATH), { recursive: true });
    writeFileSync(BASELINE_PATH, rendered, "utf8");
    console.log(`Updated ${baseline}`);
    return 0;
  }
  const { ok, line } = compareApi(rendered);
  if (!ok) {
    console.error(
      `${baseline} is stale from line ${line}: the public API changed. ` +
        `Review the change, run \`${UPDATE_COMMAND}\` and commit the baseline.`,
    );
    return 1;
  }
  console.log(`${baseline} matches the public API`);
  return 0;
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = main(process.argv.slice(2));
}
